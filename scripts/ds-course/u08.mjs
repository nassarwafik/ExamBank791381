const TO_STACK = `
public static Stack<int> ToStack(Node<int> chain)
{
    Stack<int> s = new Stack<int>();
    Node<int> pos = chain;
    while (pos != null)
    {
        s.Push(pos.GetValue());
        pos = pos.GetNext();
    }
    return s;
}`;
const MIX = `
public static void Mix(Stack<int> s, Queue<int> q)
{
    while (!s.IsEmpty())
    {
        int x = s.Pop();
        if (x % 2 == 0)
            q.Insert(x);
        else
            q.Insert(q.Remove());
    }
}`;
const FILL = `
public static void Fill(BinNode<int> bt, Stack<int> s)
{
    if (bt == null)
        return;
    Fill(bt.GetLeft(), s);
    s.Push(bt.GetValue());
    Fill(bt.GetRight(), s);
}`;
const PRINT_REVERSED = `
public static void PrintReversed(Node<int> chain)
{
    if (chain == null)
        return;
    PrintReversed(chain.GetNext());
    Console.Write(chain.GetValue() + " ");
}`;
const MERGE = `
public static Queue<int> Merge(Queue<int> q1, Queue<int> q2)
{
    Queue<int> res = new Queue<int>();
    while (!q1.IsEmpty() && !q2.IsEmpty())
    {
        if (q1.Head() <= q2.Head())
            res.Insert(q1.Remove());
        else
            res.Insert(q2.Remove());
    }
    while (!q1.IsEmpty())
        res.Insert(q1.Remove());
    while (!q2.IsEmpty())
        res.Insert(q2.Remove());
    return res;
}`;
const IS_PALINDROME = `
public static bool IsPalindrome(Node<int> chain)
{
    Stack<int> s = new Stack<int>();
    Node<int> pos = chain;
    while (pos != null)
    {
        s.Push(pos.GetValue());
        pos = pos.GetNext();
    }
    pos = chain;
    while (pos != null)
    {
        if (pos.GetValue() != s.Pop())
            return false;
        pos = pos.GetNext();
    }
    return true;
}`;
