const FIB_ITERATIVE = `
public static int Fib_Iterative(int n)
{
    if (n == 0 || n == 1)
        return n;
    int BeforeLast = 0;
    int Last = 1;
    int Current = 1;
    for (int i = 2; i <= n; i++)
    {
        Current = BeforeLast + Last;
        BeforeLast = Last;
        Last = Current;
    }
    return Current;
}`;
