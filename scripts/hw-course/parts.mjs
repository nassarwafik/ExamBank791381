// Every model is the platform's own Interactive3DSceneSpecV1 (src/interactive3d/sceneSpec.ts): boxes, cylinders, spheres …, drawn by
// the platform's SVG renderer. They are SIMPLIFIED TEACHING MODELS (the shape and the place of each piece), not photographs or CAD
// drawings. Every piece the learner can choose is an object target with a short explanation in simple Arabic.
// y is up; sizes are in arbitrary units. Palette (1..8): 1 light grey · 2 light blue · 3 blue · 4 dark blue · 5 green · 6 red · 7 gold · 8 grey.

const v = (x, y, z) => ({ x, y, z });
/** A piece: [id, label, kind, center, size, palette, rotation?, opacity?]. */
const o = (id, label, kind, center, size, palette, rotation, opacity) => ({ id, label, kind, center, size, palette, ...(rotation ? { rotation } : {}), ...(opacity ? { opacity } : {}) });
const scene = (id, title, description, objects, details, camera = { yaw: -0.6, pitch: 0.55, zoom: 1 }) => {
  for (const k of Object.keys(details)) if (!objects.some(x => x.id === k)) throw new Error(id + ": no piece " + k);
  return {
    version: 1, id, title, description, camera,
    interaction: { rotate: true, zoom: true, select: true },
    objects,
    targets: objects.filter(x => details[x.id]).map(x => ({ id: x.id, kind: "object", label: x.label, objectId: x.id, detail: details[x.id] })),
  };
};
