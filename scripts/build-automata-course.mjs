#!/usr/bin/env node
// AUTO-A2 (docs/enterprise-automata-course-a2.md) — builds the course «الوحدة الخامسة: الأتمتة» from its authored units.
//
//   node scripts/build-automata-course.mjs          write src/learning/content/<id>/manifest.ts and modules/mNN.ts
//   node scripts/build-automata-course.mjs --check  exit 1 when the committed files differ from what the units produce
//
// Every unit is authored once in scripts/automata-course/uNN.mjs (helpers: dsl.mjs). This script numbers everything (stable ids from
// the authored order: `<id>-mNN-lNN-pNN`, block ids `mNN-lNN-pNN-bNN`), fills each page's source (the deck and slides it translates,
// or «إثراء» for an added page), drops the authoring-only fields (`_lang`, `_prove` …) and writes TypeScript modules in the same
// JSON-literal style as the other generated courses. automata-course.sync.test.ts runs `render()` and compares it with the files.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COURSE, UNITS } from "./automata-course/index.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DECKS = { S1: "اللقاء 1", S2: "اللقاء 2", S3: "اللقاء 3", S4: "اللقاء 4", S5: "اللقاء 5", S6: "اللقاء 6", EX: "أمثلة من الحياة اليومية", "PDA-SIM": "محاكاة أوتومات المكدّس", "TM-HW": "وظائف آلة تورنغ" };
const pad = n => String(n).padStart(2, "0");

/** "S1 9–13" → a page source. A page without `src` is added enrichment (its source names the unit's first slide). */
function sourceOf(src, unitSrc) {
  const s = src ?? unitSrc;
  const m = /^(S[1-6]|EX|PDA-SIM|TM-HW) (\d+)(?:[–-](\d+))?$/.exec(s);
  if (!m) throw new Error("bad source: " + s);
  const [, deck, a, b] = m;
  const note = (DECKS[deck] ?? deck) + " · " + (b ? "الشرائح " + a + "–" + b : "الشريحة " + a);
  return { kind: "book", sourceId: COURSE.id, pdfPageStart: Number(a), ...(b ? { pdfPageEnd: Number(b) } : {}), sourceNote: src ? note : "إثراء (ليس من الشرائح) · يتبع " + note };
}

/** Drops authoring-only fields (names starting with "_") and functions, recursively. */
function clean(v) {
  if (Array.isArray(v)) return v.map(clean);
  if (v && typeof v === "object") {
    const out = {};
    for (const [k, x] of Object.entries(v)) if (!k.startsWith("_") && typeof x !== "function" && x !== undefined) out[k] = clean(x);
    return out;
  }
  return v;
}

/** The whole course: modules with numbered ids, plus the raw blocks (authoring fields kept) for the proof test. */
export function buildCourse() {
  const modules = [], raw = [];
  UNITS.forEach((u, ui) => {
    const mid = "m" + pad(u.n);
    const lessons = u.lessons.map((l, li) => {
      const lid = mid + "-l" + pad(li + 1);
      return {
        id: COURSE.id + "-" + lid, title: l.title, order: li + 1,
        pages: l.pages.map((p, pi) => {
          const pid = lid + "-p" + pad(pi + 1);
          const blocks = p.blocks.map((b, bi) => {
            const id = pid + "-b" + pad(bi + 1);
            raw.push({ unit: u.n, pageId: COURSE.id + "-" + pid, block: { ...b, id } });
            return clean({ id, ...b });
          });
          return {
            id: COURSE.id + "-" + pid, title: p.title, order: pi + 1, source: sourceOf(p.src, u.src),
            ...(p.layout ? { layout: p.layout } : {}), ...(p.objective ? { learningObjective: p.objective } : {}),
            ...(p.keywords ? { keywords: p.keywords } : {}), ...(p.note ? { conversionNote: p.note } : {}), blocks,
          };
        }),
      };
    });
    modules.push({ id: COURSE.id + "-" + mid, title: u.title, ...(u.short ? { shortTitle: u.short } : {}), ...(u.description ? { description: u.description } : {}), order: ui + 1, lessons });
  });
  return { modules, raw };
}

const HEADER = (what) => `// Learning Materials — «${COURSE.title}» (course ${COURSE.id}), ${what}.
//
// GENERATED by scripts/build-automata-course.mjs from scripts/automata-course/ (do not edit by hand: change the unit and re-run it).
// Source: the slides of the teacher-training course «מודלים חישוביים» (Hebrew), translated to Arabic; a page's source names the deck
// and the slides it translates. Blocks translated from the slides are origin "book"; everything added (exercises, «نحلّ معًا», the
// simulator, illustrations, clarifications) is origin "teacher-enrichment".
`;

/** The files the course consists of: path → text. */
export function render() {
  const { modules } = buildCourse();
  const files = {};
  const dir = `src/learning/content/${COURSE.id}`;
  modules.forEach((m, i) => {
    const name = "m" + pad(UNITS[i].n);
    files[`${dir}/modules/${name}.ts`] = HEADER(`unit ${UNITS[i].n} «${m.title}»`)
      + `\nimport type { ContentModule } from "../../types";\n\nconst ${name}: ContentModule = ${JSON.stringify(m, null, 2)};\n\nexport default ${name};\n`;
  });
  const manifest = {
    schemaVersion: "__SCHEMA__", courseId: COURSE.id, title: COURSE.title, direction: "rtl",
    modules: modules.map(m => ({
      id: m.id, title: m.title, ...(m.shortTitle ? { shortTitle: m.shortTitle } : {}), order: m.order,
      lessons: m.lessons.map(l => ({ id: l.id, title: l.title, order: l.order, pages: l.pages.map(p => ({ id: p.id, title: p.title, order: p.order, source: p.source, ...(p.keywords ? { keywords: p.keywords } : {}) })) })),
    })),
    batches: COURSE.batches.map(b => ({ id: b.id, label: b.label, moduleIds: b.units.map(n => COURSE.id + "-m" + pad(n)) })),
  };
  // the per-course lists elsewhere in the repository, between «BEGIN 899271» / «END 899271» marker lines (so they never drift)
  const ids = modules.map(m => m.id);
  const region = (rel, indent, body) => {
    const text = readFileSync(join(ROOT, rel), "utf8");
    const re = new RegExp("(\\n" + indent + "// BEGIN " + COURSE.id + "[^\\n]*\\n)[\\s\\S]*?(" + indent + "// END " + COURSE.id + ")");
    if (!re.test(text)) throw new Error("no BEGIN/END " + COURSE.id + " markers in " + rel);
    files[rel] = text.replace(re, (_, a, b) => a + body.map(l => indent + l + "\n").join("") + b);
  };
  region("src/learning/content/registry.ts", "  ", [`"${COURSE.id}": [`, ...ids.map(id => `  "${id}",`), "],"]);
  region("src/learning/content/bundledModules.ts", "  ", [`"${COURSE.id}": {`, ...ids.map(id => `  "${id}": () => import("./${COURSE.id}/modules/${id.slice(COURSE.id.length + 1)}"),`), "},"]);
  region("api/src/lib/learning-materials-registry.js", "  ", ["{", `  courseId: "${COURSE.id}",`, `  title: "${COURSE.title}",`, `  subject: "${COURSE.subject}",`, "  modules: [",
    ...modules.map((m, i) => `    { moduleId: "${m.id}", title: "${m.title}", order: ${m.order} }${i < modules.length - 1 ? "," : ""}`), "  ]", "}"]);
  region("src/learning/catalog.ts", "      ", COURSE.batches.map(b => `{ id: "${b.id}", label: "${b.label}" },`));
  files[`${dir}/manifest.ts`] = HEADER("content MANIFEST")
    + `//\n// ID policy: \`${COURSE.id}\` · \`${COURSE.id}-mNN\` · \`${COURSE.id}-mNN-lNN\` · \`${COURSE.id}-mNN-lNN-pNN\` — stable, never regenerated at runtime.\n`
    + `\nimport { LEARNING_CONTENT_SCHEMA_VERSION, type LearningCourseManifest } from "../types";\n\nconst manifest: LearningCourseManifest = `
    + JSON.stringify(manifest, null, 2).replace('"__SCHEMA__"', "LEARNING_CONTENT_SCHEMA_VERSION") + `;\n\nexport default manifest;\n`;
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = render();
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const abs = join(ROOT, rel);
    const now = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (now === text) continue;
    stale++;
    if (check) { console.error("stale: " + rel); continue; }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
    console.log("wrote " + rel);
  }
  if (check && stale) process.exit(1);
  console.log(check ? "up to date" : `${Object.keys(files).length} files, ${stale} written`);
}
