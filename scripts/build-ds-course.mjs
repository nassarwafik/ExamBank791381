#!/usr/bin/env node
// DS-A2 (docs/enterprise-data-structures-course.md) — builds the course «مبنى المعطيات» from its authored units.
//
//   node scripts/build-ds-course.mjs          write src/learning/content/<id>/manifest.ts and modules/mNN.ts
//   node scripts/build-ds-course.mjs --check  exit 1 when the committed files differ from what the units produce
//
// Every unit is authored once in scripts/ds-course/uNN.mjs (helpers: dsl.mjs). This script numbers everything (stable ids from the
// authored order: `<id>-mNN-lNN-pNN`, block ids `mNN-lNN-pNN-bNN`), fills each page's source (the book pages it comes from, or
// «إثراء» for an added page), drops the authoring-only fields (`_prog`, `_prove` …) and writes TypeScript modules in the same
// JSON-literal style as the other generated courses. course899271d.test.ts runs `render()` and compares it with the files.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COURSE, UNITS, CHAPTERS } from "./ds-course/index.mjs";
import { iso, LRI, PDI } from "./ds-course/dsl.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const pad = n => String(n).padStart(2, "0");

/** The book chapter a printed page belongs to. */
export const chapterOf = page => CHAPTERS.find(c => page >= c.from && page <= c.to);
/** "180–181" (the book's printed pages) → a page source. A page without `src` is added enrichment (it follows the unit's first page). */
function sourceOf(src, unitSrc) {
  const m = /^(\d+)(?:[–-](\d+))?$/.exec(src ?? unitSrc);
  if (!m) throw new Error("bad source: " + (src ?? unitSrc));
  const a = Number(m[1]), b = m[2] ? Number(m[2]) : undefined;
  const ch = chapterOf(a);
  if (!ch || (b !== undefined && (b < a || chapterOf(b) !== ch))) throw new Error("source pages outside one chapter: " + (src ?? unitSrc));
  const note = ch.label + " · " + (b ? "ص " + a + "–" + b : "ص " + a);
  return { kind: "book", sourceId: COURSE.id, pdfPageStart: a, ...(b ? { pdfPageEnd: b } : {}), sourceNote: src ? note : "إثراء (ليس من الكتاب) · يتبع " + ch.label };
}

/** Drops authoring-only fields (names starting with "_") and functions, recursively. */
function clean(v) {
  if (Array.isArray(v)) return v.map(clean);
  if (v && typeof v === "object") {
    const out = {};
    for (const [k, x] of Object.entries(v)) if (!k.startsWith("_") && typeof x !== "function" && x !== undefined) out[k] = clean(x);
    return out;
  }
  return v;
}

/** The whole course: modules with numbered ids, plus the raw blocks (authoring fields kept) for the proof test. */
export function buildCourse(units = UNITS) {
  const modules = [], raw = [];
  units.forEach((u, ui) => {
    const mid = "m" + pad(u.n);
    // a unit's title is listed by the server registry and the library: plain words only (code such as Stack<T> would be reordered)
    for (const t of [u.title, u.short, u.description]) if (/[`<>]/.test(t ?? "")) throw new Error("unit " + u.n + ": no code in a unit's title / description: " + t);
    const lessons = u.lessons.map((l, li) => {
      const lid = mid + "-l" + pad(li + 1);
      return {
        id: COURSE.id + "-" + lid, title: iso(l.title), order: li + 1,
        pages: l.pages.map((p, pi) => {
          const pid = lid + "-p" + pad(pi + 1);
          const blocks = p.blocks.map((b, bi) => {
            const id = pid + "-b" + pad(bi + 1);
            raw.push({ unit: u.n, pageId: COURSE.id + "-" + pid, enrichmentPage: !p.src, block: { ...b, id } });
            return clean({ id, ...b });
          });
          return {
            id: COURSE.id + "-" + pid, title: iso(p.title), order: pi + 1, source: sourceOf(p.src, u.src),
            ...(p.layout ? { layout: p.layout } : {}), ...(p.objective ? { learningObjective: iso(p.objective) } : {}),
            ...(p.keywords ? { keywords: p.keywords } : {}), ...(p.note ? { conversionNote: p.note } : {}), blocks,
          };
        }),
      };
    });
    modules.push({ id: COURSE.id + "-" + mid, title: u.title, ...(u.short ? { shortTitle: u.short } : {}), ...(u.description ? { description: u.description } : {}), order: ui + 1, lessons });
  });
  return { modules, raw };
}

const HEADER = (what) => `// Learning Materials — «${COURSE.title}» (course ${COURSE.id}), ${what}.
//
// GENERATED by scripts/build-ds-course.mjs from scripts/ds-course/ (do not edit by hand: change the unit and re-run it).
// Source: the book «مقدّمة في مباني المعلومات بلغة C#»; a page's source names the chapter and the book pages it comes from. What the
// book says is origin "book"; everything added (the traces, the lab, the drawings, exercises, «نحلّ معًا», clarifications) is origin
// "teacher-enrichment".
`;

/**
 * JSON for a generated source file: the invisible isolates are written as escapes, so a reviewer sees them; and the recorded steps
 * of a trace are written one step per line (a step is a snapshot of nested frames and objects: indented, a trace would be pages).
 */
function json(v, indent) {
  const steps = [];
  const text = JSON.stringify(v, (key, value) => (key === "steps" && Array.isArray(value) && value.length && "l" in value[0] ? "__STEPS_" + (steps.push(value) - 1) + "__" : value), indent);
  return text.replace(/"__STEPS_(\d+)__"/g, (_, i) => "[\n" + steps[Number(i)].map(st => JSON.stringify(st)).join(",\n") + "\n]")
    .replaceAll(LRI, "\\u2066").replaceAll(PDI, "\\u2069");
}

/** The files the course consists of: path → text. */
export function render() {
  const { modules } = buildCourse();
  const files = {};
  const dir = `src/learning/content/${COURSE.id}`;
  modules.forEach((m, i) => {
    const name = "m" + pad(UNITS[i].n);
    files[`${dir}/modules/${name}.ts`] = HEADER(`unit ${UNITS[i].n} «${m.title}»`)
      + `\nimport type { ContentModule } from "../../types";\n\nconst ${name}: ContentModule = ${json(m, 1)};\n\nexport default ${name};\n`;
  });
  const manifest = {
    schemaVersion: "__SCHEMA__", courseId: COURSE.id, title: COURSE.title, direction: "rtl",
    modules: modules.map(m => ({
      id: m.id, title: m.title, ...(m.shortTitle ? { shortTitle: m.shortTitle } : {}), order: m.order,
      lessons: m.lessons.map(l => ({ id: l.id, title: l.title, order: l.order, pages: l.pages.map(p => ({ id: p.id, title: p.title, order: p.order, source: p.source, ...(p.keywords ? { keywords: p.keywords } : {}) })) })),
    })),
    batches: COURSE.batches.map(b => ({ id: b.id, label: b.label, moduleIds: b.units.map(n => COURSE.id + "-m" + pad(n)) })),
  };
  // the per-course lists elsewhere in the repository, between «BEGIN <id>» / «END <id>» marker lines (so they never drift)
  const ids = modules.map(m => m.id);
  const region = (rel, indent, body) => {
    const text = readFileSync(join(ROOT, rel), "utf8");
    const re = new RegExp("(\\n" + indent + "// BEGIN " + COURSE.id + "(?![A-Za-z0-9])[^\\n]*\\n)[\\s\\S]*?(" + indent + "// END " + COURSE.id + "(?![A-Za-z0-9]))");
    if (!re.test(text)) throw new Error("no BEGIN/END " + COURSE.id + " markers in " + rel);
    files[rel] = text.replace(re, (_, a, b) => a + body.map(l => indent + l + "\n").join("") + b);
  };
  region("src/learning/content/registry.ts", "  ", [`"${COURSE.id}": [`, ...ids.map(id => `  "${id}",`), "],"]);
  region("src/learning/content/bundledModules.ts", "  ", [`"${COURSE.id}": {`, ...ids.map(id => `  "${id}": () => import("./${COURSE.id}/modules/${id.slice(COURSE.id.length + 1)}"),`), "},"]);
  region("api/src/lib/learning-materials-registry.js", "  ", ["{", `  courseId: "${COURSE.id}",`, `  title: "${COURSE.title}",`, `  subject: "${COURSE.subject}",`, "  modules: [",
    ...modules.map((m, i) => `    { moduleId: "${m.id}", title: "${m.title}", order: ${m.order} }${i < modules.length - 1 ? "," : ""}`), "  ]", "},"]);
  region("src/learning/catalog.ts", "      ", COURSE.batches.map(b => `{ id: "${b.id}", label: "${b.label}" },`));
  files[`${dir}/manifest.ts`] = HEADER("content MANIFEST")
    + `//\n// ID policy: \`${COURSE.id}\` · \`${COURSE.id}-mNN\` · \`${COURSE.id}-mNN-lNN\` · \`${COURSE.id}-mNN-lNN-pNN\` — stable, never regenerated at runtime.\n`
    + `\nimport { LEARNING_CONTENT_SCHEMA_VERSION, type LearningCourseManifest } from "../types";\n\nconst manifest: LearningCourseManifest = `
    + json(manifest, 2).replace('"__SCHEMA__"', "LEARNING_CONTENT_SCHEMA_VERSION") + `;\n\nexport default manifest;\n`;
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = render();
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const abs = join(ROOT, rel);
    const now = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (now === text) continue;
    stale++;
    if (check) { console.error("stale: " + rel); continue; }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
    console.log("wrote " + rel);
  }
  if (check && stale) process.exit(1);
  console.log(check ? "up to date" : `${Object.keys(files).length} files, ${stale} written`);
}
