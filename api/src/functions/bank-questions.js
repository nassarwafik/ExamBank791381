/*
 * UX-6c — Question Bank management (list / create / update / delete) over the EXISTING bank store:
 *   bank/index/questions-index.json   lightweight index the builder selects from (no text)
 *   bank/sources/<sourceId>.json      { questions: [full bank question] } — official builds, file imports, and
 *                                     (new here) teacher-entered questions under sources/manual.json
 * No second storage system: the same layout bank-import-action.js commits to and question-bank-action.js reads.
 * Official sources (791381-20xx / 791367-20xx, examCode 791381/791367) are generated by build-bank-2025 and are
 * READ-ONLY here; the bundled exam-library (api/src/data) is a different, read-only dataset and is never touched.
 * Saved exams store question SNAPSHOTS (exams/*.json carry full text/options; bankQuestionId is only a dedupe
 * reference), so deleting a bank question never breaks a saved exam.
 *
 * Canonical shapes (the SAME the Builder converts through ../lib/bank-question-exam.js — see that file):
 *   multipleChoice → type "multipleChoice", options[{value,label,text,textHtml,order}], answer singleChoice
 *   fillBlank      → type "multiField", fields[{id,label,labelHtml,order,kind:"text",correct}], answer exactSequence
 *   wordBank       → type "multiField", fields[… kind:"select", options[{value,label,text,textHtml,order}], correct]
 *                    + wordBank[string], answer exactSequence
 *   open           → type "shortAnswer", answer anyAccepted / manual
 * A type switch REBUILDS the structure: options / fields / wordBank / answer are always written whole, never merged.
 *
 * Write consistency (two blobs, no transaction): every operation is IDEMPOTENT RECONCILIATION. The source document
 * is written first and is the authority; the index is then reconciled FROM the stored question. If the second write
 * fails the client gets an error and the SAME request converges on retry:
 *   create  — the id is derived from the client's requestKey (manual-<requestKey>); a retry finds the identical
 *             question already stored, skips the source write and only reconciles the index (never a second copy).
 *             The same id with DIFFERENT content is a 409, never an overwrite.
 *   update  — re-applies the same content to the source and re-derives the index entry from what is stored.
 *   delete  — removes whichever half still exists (source and/or index); 404 only when neither has the question.
 * locate() also self-heals: an index entry whose source no longer holds the question is dropped from the index.
 * Concurrency: every write goes through mutateJsonWithRetry (ETag-conditional upload with retries).
 */
const BANK_CONTAINER = "bank";
const INDEX_BLOB = "index/questions-index.json";
const SOURCES_PREFIX = "sources/";
const MANUAL_SOURCE_ID = "manual";
const PRESENTATION_TYPES = ["multipleChoice", "fillBlank", "wordBank", "open"];
const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,120}$/;
const REQUEST_KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9_-]{7,63}$/;
const FIELD_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9_-]{0,40}$/;
const MAX_TEXT = 5000, MAX_TOPIC = 80, MAX_OPTION = 500, MAX_OPTIONS = 12, MAX_VALUES = 20, MAX_VALUE = 500, MAX_FIELDS = 20, MAX_WORDS = 40;

function getBankContainer() {
  const cs = process.env.AZURE_STORAGE_CONNECTION_STRING;
  if (!cs) throw new Error("AZURE_STORAGE_CONNECTION_STRING is not configured.");
  return BlobServiceClient.fromConnectionString(cs).getContainerClient(BANK_CONTAINER);
}

function isOfficialSource(sourceId, examCode) {
  const s = String(sourceId || ""), e = String(examCode || "");
  return /^791381-20\d{2}/.test(s) || /^791367-20\d{2}/.test(s) || e === "791381" || e === "791367";
}
function sourceKind(sourceId) {
  if (isOfficialSource(sourceId)) return "official";
  if (String(sourceId) === MANUAL_SOURCE_ID) return "manual";
  return "import";
}

// Exactly the Builder's classification (shared helper) — a stored question is what the Builder will see.
const presentationTypeFromBankQuestion = presentationTypeFromFullQuestion;
function presentationTypeToBankType(presentationType) {
  if (presentationType === "multipleChoice") return "multipleChoice";
  if (presentationType === "fillBlank" || presentationType === "wordBank") return "multiField";
  return "shortAnswer";
}
const optionText = o => String(o?.text ?? o?.label ?? o?.value ?? "").trim();
function wordBankOf(question) {
  if (Array.isArray(question.wordBank) && question.wordBank.length) return question.wordBank.map(w => String(w ?? "").trim()).filter(Boolean);
  const values = [];
  for (const f of Array.isArray(question.fields) ? question.fields : []) for (const o of Array.isArray(f?.options) ? f.options : []) { const t = optionText(o); if (t && !values.includes(t)) values.push(t); }
  return values;
}

// One row per bank question: text/options/fields/answer from the source document (authoritative content), topic /
// difficulty / section / reviewStatus from the index entry when present (what the builder selects on). The row is
// the editable projection: fields carry their expected value (teacher-side endpoint) and a word-bank question its choices.
function toRow(question, indexEntry, sourceId) {
  const cls = question.classification || {};
  const idx = indexEntry || {};
  const official = isOfficialSource(sourceId, question.examCode);
  const presentationType = presentationTypeFromBankQuestion(question);
  return {
    id: String(question.id),
    sourceId: String(sourceId),
    sourceKind: sourceKind(sourceId),
    official,
    questionNumber: String(question.questionNumber ?? idx.questionNumber ?? ""),
    section: String(idx.section || question.section || ""),
    topic: String(idx.topic || cls.topic || ""),
    difficulty: Number.isFinite(Number(idx.difficulty ?? cls.difficulty)) && (idx.difficulty ?? cls.difficulty) !== null ? Number(idx.difficulty ?? cls.difficulty) : null,
    difficultyLabel: String(idx.difficultyLabel || cls.difficultyLabel || ""),
    type: String(question.type || idx.type || ""),
    presentationType,
    text: String(question.text || ""),
    options: (Array.isArray(question.options) ? question.options : []).map((o, i) => ({ value: String(o.value ?? i), text: String(o.text ?? o.label ?? "") })),
    fields: (Array.isArray(question.fields) ? question.fields : []).map((f, i) => ({ id: String(f.id ?? i + 1), label: String(f.label ?? ""), correct: f.correct === undefined || f.correct === null ? "" : String(f.correct) })),
    wordBank: presentationType === "wordBank" ? wordBankOf(question) : [],
    answer: question.answer && typeof question.answer === "object" ? question.answer : {},
    hasImage: (Array.isArray(question.assets) && question.assets.length > 0) || idx.hasImage === true,
    reviewStatus: String(idx.reviewStatus || question.reviewStatus || ""),
    createdAt: String(question.createdAt || ""),
    updatedAt: String(question.updatedAt || "")
  };
}

// Server-side validation of the editable payload. Same rules the builder's quality checks and the import gate
// apply: exact section, non-empty text, ≥ 2 options with a designated correct one for multiple choice, ≥ 1 blank
// with an expected value for fill-blank / word-bank (and every expected value offered by the word bank), integer
// difficulty 1..5, known presentation type. Returns { ok, errors[] } — every error is an actionable Arabic message.
function validateQuestionInput(input) {
  const errors = [];
  const q = input && typeof input === "object" ? input : {};
  const text = String(q.text ?? "").trim();
  if (!text) errors.push("نص السؤال مطلوب.");
  else if (text.length > MAX_TEXT) errors.push("نص السؤال أطول من المسموح (" + MAX_TEXT + " حرفًا).");
  if (!VALID_SECTIONS.includes(q.section)) errors.push("القسم يجب أن يكون BASIC أو INFRASTRUCTURE.");
  const topic = String(q.topic ?? "").trim();
  if (!topic) errors.push("الموضوع مطلوب.");
  else if (topic.length > MAX_TOPIC) errors.push("الموضوع أطول من المسموح.");
  const difficulty = Number(q.difficulty);
  if (!Number.isInteger(difficulty) || difficulty < 1 || difficulty > 5) errors.push("الصعوبة يجب أن تكون رقمًا من 1 إلى 5.");
  if (!PRESENTATION_TYPES.includes(q.presentationType)) errors.push("نوع السؤال غير معروف.");
  const options = Array.isArray(q.options) ? q.options : [];
  const answer = q.answer && typeof q.answer === "object" ? q.answer : {};
  if (q.presentationType === "multipleChoice") {
    if (options.length < 2) errors.push("سؤال الاختيار من متعدد يحتاج خيارين على الأقل.");
    if (options.length > MAX_OPTIONS) errors.push("عدد الخيارات أكبر من المسموح.");
    options.forEach((o, i) => {
      const t = String(o?.text ?? "").trim();
      if (!t) errors.push("الخيار " + (i + 1) + " بلا نص.");
      else if (t.length > MAX_OPTION) errors.push("الخيار " + (i + 1) + " أطول من المسموح.");
    });
    const correct = String(answer.correctOptionValue ?? "").trim();
    if (!correct || !options.some((o, i) => String(o?.value ?? i) === correct)) errors.push("حدّد الإجابة الصحيحة من بين الخيارات.");
  } else if (q.presentationType === "fillBlank" || q.presentationType === "wordBank") {
    const fields = Array.isArray(q.fields) ? q.fields : [];
    if (fields.length < 1) errors.push("أضف فراغًا واحدًا على الأقل.");
    if (fields.length > MAX_FIELDS) errors.push("عدد الفراغات أكبر من المسموح.");
    const words = q.presentationType === "wordBank" ? Array.from(new Set((Array.isArray(q.wordBank) ? q.wordBank : []).map(w => String(w ?? "").trim()).filter(Boolean))) : [];
    fields.forEach((f, i) => {
      const correct = String(f?.correct ?? "").trim();
      if (String(f?.label ?? "").trim().length > MAX_OPTION) errors.push("عنوان الفراغ " + (i + 1) + " أطول من المسموح.");
      if (!correct) errors.push("الفراغ " + (i + 1) + " بلا إجابة صحيحة.");
      else if (correct.length > MAX_VALUE) errors.push("إجابة الفراغ " + (i + 1) + " أطول من المسموح.");
      else if (q.presentationType === "wordBank" && words.length && !words.includes(correct)) errors.push("الإجابة الصحيحة للفراغ " + (i + 1) + " غير موجودة في بنك الكلمات.");
    });
    if (q.presentationType === "wordBank") {
      if (words.length < 2) errors.push("بنك الكلمات يحتاج كلمتين مختلفتين على الأقل.");
      if (words.length > MAX_WORDS) errors.push("عدد كلمات بنك الكلمات أكبر من المسموح.");
      words.forEach((w, i) => { if (w.length > MAX_VALUE) errors.push("الكلمة " + (i + 1) + " في بنك الكلمات أطول من المسموح."); });
    }
  } else {
    const values = Array.isArray(answer.values) ? answer.values : [];
    if (values.length > MAX_VALUES) errors.push("عدد الإجابات المقبولة أكبر من المسموح.");
    values.forEach((v, i) => { if (String(v ?? "").trim().length > MAX_VALUE) errors.push("الإجابة المقبولة " + (i + 1) + " أطول من المسموح."); });
  }
  return { ok: errors.length === 0, errors };
}

// Normalizes a validated payload into the canonical bank question content. The structure is rebuilt WHOLE for the
// target type (options / fields / wordBank / answer), so switching a question's type can never leave a stale
// structure from the previous type behind.
function normalizeInput(q) {
  const presentationType = q.presentationType;
  const base = { section: q.section, type: presentationTypeToBankType(presentationType), text: String(q.text).trim(), textHtml: "", topic: String(q.topic).trim(), difficulty: Number(q.difficulty) };
  if (presentationType === "multipleChoice") {
    const options = q.options.map((o, i) => { const value = String(o.value ?? i).trim() || String(i); const text = String(o.text).trim(); return { value, label: text, text, textHtml: "", order: i }; });
    const correct = String(q.answer.correctOptionValue).trim();
    const index = options.findIndex(o => o.value === correct);
    const answer = { mode: "singleChoice", correctOptionValue: correct, correctOptionIndex: index, correctText: options[index]?.text || null, values: [correct] };
    return { ...base, options, fields: [], wordBank: [], answer, flags: { hasOptions: true, requiresManualReview: false } };
  }
  if (presentationType === "fillBlank" || presentationType === "wordBank") {
    const isBank = presentationType === "wordBank";
    const words = isBank ? Array.from(new Set(q.wordBank.map(w => String(w ?? "").trim()).filter(Boolean))) : [];
    const choiceOptions = words.map((w, i) => ({ value: w, label: w, text: w, textHtml: "", order: i }));
    const used = new Set();
    const fields = q.fields.map((f, i) => {
      const wanted = String(f?.id ?? "").trim();
      let id = FIELD_ID_PATTERN.test(wanted) && !used.has(wanted) ? wanted : "f" + (i + 1);
      while (used.has(id)) id += "_";
      used.add(id);
      const label = String(f?.label ?? "").trim();
      const field = { id, label, labelHtml: "", order: i + 1, kind: isBank ? "select" : "text", correct: String(f.correct).trim() };
      if (isBank) field.options = choiceOptions.map(o => ({ ...o }));
      return field;
    });
    const answer = { mode: "exactSequence", values: fields.map(f => f.correct) };
    return { ...base, options: [], fields, wordBank: words, answer, flags: { hasOptions: false, requiresManualReview: false } };
  }
  const values = (Array.isArray(q.answer?.values) ? q.answer.values : []).map(v => String(v).trim()).filter(Boolean);
  const answer = values.length ? { mode: "anyAccepted", values } : { mode: "manual", values: [] };
  return { ...base, options: [], fields: [], wordBank: [], answer, flags: { hasOptions: false, requiresManualReview: answer.mode === "manual" } };
}

// What "the same question" means for an idempotent create retry: the whole normalized content + classification.
function contentKey(question) {
  const cls = question.classification || {};
  return JSON.stringify({ section: question.section, type: question.type, text: question.text, options: question.options || [], fields: question.fields || [], wordBank: question.wordBank || [], answer: question.answer || {}, topic: cls.topic ?? question.topic, difficulty: cls.difficulty ?? question.difficulty });
}
function newQuestionId() {
  return MANUAL_SOURCE_ID + "-" + Date.now().toString(36) + "-" + crypto.randomBytes(3).toString("hex");
}
function questionIdForRequestKey(requestKey) {
  const key = String(requestKey ?? "").trim();
  return REQUEST_KEY_PATTERN.test(key) ? MANUAL_SOURCE_ID + "-" + key : null;
}
function toIndexEntry(question, sourceId, previous) {
  const cls = question.classification || {};
  return {
    ...(previous || {}),
    id: question.id, sourceId, sourcePriority: previous?.sourcePriority ?? 0,
    questionNumber: question.questionNumber || "", section: question.section, type: question.type, originalType: previous?.originalType || question.type,
    topic: cls.topic || "UNKNOWN", difficulty: cls.difficulty ?? null, familyKey: cls.familyKey || "",
    hasImage: (question.assets || []).length > 0, assetCount: (question.assets || []).length, reviewStatus: question.reviewStatus,
    secondaryTopics: cls.secondaryTopics || [], difficultyLabel: cls.difficultyLabel || "", hasCLI: previous?.hasCLI === true, requiresCalculation: previous?.requiresCalculation === true,
    needsReview: question.flags?.requiresManualReview === true, classificationConfidence: cls.difficultyConfidence ?? null
  };
}
const bad = (status, error, extra) => ({ status, jsonBody: { ok: false, error, ...(extra || {}) } });
const SKIP = Symbol("skip-write");

async function handler(request, deps = {}, obs = null) {
  const authFn = deps.requireBuilderAuth || requireBuilderAuth;
  const getBank = deps.getBankContainer || getBankContainer;
  const dl = deps.downloadJsonOrNull || downloadJsonOrNull;
  const ls = deps.listJson || listJson;
  const mutateRaw = deps.mutateJsonWithRetry || mutateJsonWithRetry;
  const conflict = deps.isConcurrencyConflict || isConcurrencyConflict;
  const audit = deps.recordAuditEvent || recordAuditEvent;
  const getPlatform = deps.getPlatformContainer || getPlatformContainer;
  const now = deps.now || (() => new Date().toISOString());
  const makeId = deps.newQuestionId || newQuestionId;
  let phase = "read";
  try {
    const auth = authFn(request);
    if (!auth.ok) return auth.response;
    const bank = getBank();
    const actor = String(auth.user?.sub || auth.user?.userCode || "teacher");
    const readIndex = async () => { const index = await dl(bank, INDEX_BLOB); return Array.isArray(index?.questions) ? index.questions : []; };
    const sourceBlob = sourceId => SOURCES_PREFIX + sourceId + ".json";
    // A mutation whose function returns SKIP leaves the blob untouched (no upload) — the reconciliation steps use it
    // when the stored state already matches, so a retry never rewrites what is already correct.
    const mutate = async (blob, fn) => { try { return await mutateRaw(bank, blob, current => { const next = fn(current); if (next === SKIP) throw Object.assign(new Error("skip"), { code: "SKIP_WRITE" }); return next; }); } catch (e) { if (e?.code === "SKIP_WRITE") return null; throw e; } };
    // Reconcile the index FROM a stored question: upsert its entry (idempotent).
    const reconcileIndex = async (question, sourceId) => {
      let entry = null;
      phase = "index";
      await mutate(INDEX_BLOB, current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const previous = questions.find(e => String(e?.id) === question.id) || null;
        entry = toIndexEntry(question, sourceId, previous);
        if (previous && JSON.stringify(previous) === JSON.stringify(entry)) return SKIP;
        return { ...(current || {}), questions: [...questions.filter(e => String(e?.id) !== question.id), entry] };
      });
      return entry;
    };
    const removeFromIndex = async id => {
      let removed = false;
      phase = "index";
      await mutate(INDEX_BLOB, current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const remaining = questions.filter(e => String(e?.id) !== id);
        removed = remaining.length !== questions.length;
        return removed ? { ...(current || {}), questions: remaining } : SKIP;
      });
      return removed;
    };

    if (request.method === "GET") {
      const [entries, sources] = await Promise.all([readIndex(), ls(bank, SOURCES_PREFIX)]);
      const byId = new Map(entries.map(e => [String(e.id), e]));
      const rows = [];
      for (const document of sources) {
        for (const question of Array.isArray(document?.questions) ? document.questions : []) {
          if (!question?.id) continue;
          const sourceId = question.sourceId || byId.get(String(question.id))?.sourceId || "";
          rows.push(toRow(question, byId.get(String(question.id)), sourceId));
        }
      }
      rows.sort((a, b) => (b.updatedAt || b.createdAt || "").localeCompare(a.updatedAt || a.createdAt || "") || a.id.localeCompare(b.id));
      obs?.logInfo?.("bank.questions.listed", { rows: rows.length, sources: sources.length });
      return { status: 200, jsonBody: { ok: true, questions: rows, sections: VALID_SECTIONS, presentationTypes: PRESENTATION_TYPES } };
    }

    let body = {};
    try { body = await request.json(); } catch { body = {}; }
    const action = String(body?.action || "").trim().toLowerCase();
    if (!["create", "update", "delete"].includes(action)) return bad(400, "الإجراء غير معروف (create / update / delete).");

    // Where does the question live? The source document is the authority; the index only points at it. An index
    // entry whose source no longer holds the question (a delete whose index write failed) is dropped here.
    const locate = async id => {
      if (!ID_PATTERN.test(id)) return { error: bad(400, "معرّف السؤال غير صالح.") };
      const entry = (await readIndex()).find(e => String(e.id) === id) || null;
      const findIn = document => (Array.isArray(document?.questions) ? document.questions : []).find(q => String(q?.id) === id) || null;
      let sourceId = entry?.sourceId ? String(entry.sourceId) : "";
      let stored = sourceId ? findIn(await dl(bank, sourceBlob(sourceId))) : null;
      if (!stored) {
        sourceId = "";
        for (const document of await ls(bank, SOURCES_PREFIX)) {
          const hit = findIn(document);
          if (hit) { stored = hit; sourceId = String(hit.sourceId || document.sourceId || ""); break; }
        }
      }
      if (!stored || !sourceId) return { error: null, missing: true, entry, sourceId: "" };
      if (isOfficialSource(sourceId)) return { error: bad(403, "أسئلة البنك الرسمي للقراءة فقط ولا يمكن تعديلها أو حذفها من هنا.") };
      return { sourceId, entry, stored };
    };

    if (action === "create") {
      const check = validateQuestionInput(body?.question);
      if (!check.ok) return bad(400, check.errors[0], { errors: check.errors });
      const n = normalizeInput(body.question);
      const stamp = now();
      const id = questionIdForRequestKey(body?.requestKey) || makeId();
      if (!ID_PATTERN.test(id)) return bad(400, "معرّف الطلب غير صالح.");
      const fresh = {
        id, sourceId: MANUAL_SOURCE_ID, sourceQuestionId: id, questionNumber: "",
        section: n.section, type: n.type, text: n.text, textHtml: n.textHtml, options: n.options, fields: n.fields, wordBank: n.wordBank, parts: [], answer: n.answer, assets: [],
        flags: { hasImage: false, hasOptions: n.flags.hasOptions, isChild: false, requiresManualReview: n.flags.requiresManualReview },
        classification: { topic: n.topic, secondaryTopics: [], difficulty: n.difficulty, difficultyLabel: "", difficultyReason: "teacher-entered in Exam Bank management", difficultyConfidence: null, familyKey: null, status: "classified" },
        reviewStatus: "classified", createdBy: actor, createdAt: stamp, updatedAt: stamp
      };
      let question = fresh, alreadyStored = false;
      phase = "source";
      await mutate(sourceBlob(MANUAL_SOURCE_ID), current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const existing = questions.find(q => String(q?.id) === id);
        if (existing) {
          // Retry of a create whose index write failed: the identical question is already stored → reconcile only.
          if (contentKey(existing) !== contentKey(fresh)) throw Object.assign(new Error("duplicate id"), { code: "DUPLICATE_ID" });
          question = existing; alreadyStored = true;
          return SKIP;
        }
        return { ...(current || {}), sourceId: MANUAL_SOURCE_ID, questions: [...questions, fresh] };
      });
      const entry = await reconcileIndex(question, MANUAL_SOURCE_ID);
      await audit(getPlatform(), { actor, action: alreadyStored ? "bank.question.reindex" : "bank.question.create", targetType: "bankQuestion", targetId: id, details: { sourceId: MANUAL_SOURCE_ID, section: n.section } });
      return { status: 200, jsonBody: { ok: true, question: toRow(question, entry, MANUAL_SOURCE_ID) } };
    }

    const id = String(body?.id || "").trim();
    const found = await locate(id);
    if (found.error) return found.error;

    if (action === "update") {
      if (found.missing) {
        if (found.entry) await removeFromIndex(id);                                   // stale index entry: heal, then 404
        return bad(404, "السؤال غير موجود في بنك الأسئلة.");
      }
      const check = validateQuestionInput(body?.question);
      if (!check.ok) return bad(400, check.errors[0], { errors: check.errors });
      const n = normalizeInput(body.question);
      const stamp = now();
      let updated = null;
      phase = "source";
      await mutate(sourceBlob(found.sourceId), current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const i = questions.findIndex(q => String(q?.id) === id);
        if (i < 0) throw Object.assign(new Error("missing"), { code: "NOT_FOUND" });
        const previous = questions[i];
        // The whole type-specific structure is replaced (options / fields / wordBank / answer), never merged.
        updated = {
          ...previous, section: n.section, type: n.type, text: n.text, textHtml: n.textHtml, options: n.options, fields: n.fields, wordBank: n.wordBank, answer: n.answer,
          flags: { ...(previous.flags || {}), hasOptions: n.flags.hasOptions, requiresManualReview: n.flags.requiresManualReview },
          classification: { ...(previous.classification || {}), topic: n.topic, difficulty: n.difficulty, status: "classified" },
          reviewStatus: "classified", updatedBy: actor, updatedAt: stamp
        };
        return { ...current, questions: questions.map((q, k) => (k === i ? updated : q)) };
      });
      const entry = await reconcileIndex(updated, found.sourceId);
      await audit(getPlatform(), { actor, action: "bank.question.update", targetType: "bankQuestion", targetId: id, details: { sourceId: found.sourceId, section: n.section } });
      return { status: 200, jsonBody: { ok: true, question: toRow(updated, entry, found.sourceId) } };
    }

    // delete — the question leaves the source document and the index; image assets (if any) stay in the assets
    // container (no cascade), saved exams keep their own snapshots. Each half is removed if still present, so a
    // retry after a partial failure converges; 404 only when neither half has the question.
    let removedFromSource = false;
    if (!found.missing) {
      phase = "source";
      await mutate(sourceBlob(found.sourceId), current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const remaining = questions.filter(q => String(q?.id) !== id);
        removedFromSource = remaining.length !== questions.length;
        return removedFromSource ? { ...current, questions: remaining } : SKIP;
      });
    }
    const removedFromIndex = await removeFromIndex(id);
    if (!removedFromSource && !removedFromIndex) return bad(404, "السؤال غير موجود في بنك الأسئلة.");
    await audit(getPlatform(), { actor, action: "bank.question.delete", targetType: "bankQuestion", targetId: id, details: { sourceId: found.sourceId || String(found.entry?.sourceId || "") } });
    return { status: 200, jsonBody: { ok: true, deleted: true, id } };
  } catch (e) {
    if (e?.code === "NOT_FOUND") return bad(404, "السؤال غير موجود في بنك الأسئلة.");
    if (e?.code === "DUPLICATE_ID") return bad(409, "تعذر إنشاء السؤال: يوجد سؤال بالمعرّف نفسه بمحتوى مختلف، حدّث القائمة ثم أعد المحاولة.");
    if (conflict(e) || e?.name === "StorageConflictError") return bad(409, "تعذر الحفظ بسبب تعديل متزامن على بنك الأسئلة، أعد المحاولة.");
    obs?.logError?.("bank.questions.failed", e, { method: request.method, phase });
    return bad(500, phase === "index" ? "تم حفظ السؤال لكن تعذر تحديث فهرس البنك، أعد المحاولة لإكمال العملية." : "تعذر تنفيذ العملية على بنك الأسئلة حاليًا.");
  }
}

app.http("bankQuestions", { methods: ["GET", "POST"], authLevel: "anonymous", route: "bank-questions", handler: withObservability("bank-questions", handler) });
