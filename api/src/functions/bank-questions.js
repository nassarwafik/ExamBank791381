const { app } = require("@azure/functions");
const { BlobServiceClient } = require("@azure/storage-blob");
const crypto = require("crypto");
const { requireBuilderAuth } = require("../lib/builder-auth");
const { VALID_SECTIONS } = require("../lib/section-resolver");
const { downloadJsonOrNull, listJson, mutateJsonWithRetry, isConcurrencyConflict, getContainer: getPlatformContainer } = require("../lib/platform-storage");
const { recordAuditEvent } = require("../lib/audit-log");
const { withObservability } = require("../lib/observability");

/*
 * UX-6c — Question Bank management (list / create / update / delete) over the EXISTING bank store:
 *   bank/index/questions-index.json   lightweight index the builder selects from (no text)
 *   bank/sources/<sourceId>.json      { questions: [full bank question] } — official builds, file imports, and
 *                                     (new here) teacher-entered questions under sources/manual.json
 * No second storage system: the same layout bank-import-action.js commits to and question-bank-action.js reads.
 * Official sources (791381-20xx / 791367-20xx, examCode 791381/791367) are generated by build-bank-2025 and are
 * READ-ONLY here; the bundled exam-library (api/src/data) is a different, read-only dataset and is never touched.
 * Concurrency: every write goes through mutateJsonWithRetry (ETag-conditional upload with retries).
 * Saved exams store question SNAPSHOTS (exams/*.json carry full text/options; bankQuestionId is only a dedupe
 * reference), so deleting a bank question never breaks a saved exam.
 */
const BANK_CONTAINER = "bank";
const INDEX_BLOB = "index/questions-index.json";
const SOURCES_PREFIX = "sources/";
const MANUAL_SOURCE_ID = "manual";
const PRESENTATION_TYPES = ["multipleChoice", "fillBlank", "wordBank", "open"];
const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,120}$/;
const MAX_TEXT = 5000, MAX_TOPIC = 80, MAX_OPTION = 500, MAX_OPTIONS = 12, MAX_VALUES = 20, MAX_VALUE = 500;

function getBankContainer() {
  const cs = process.env.AZURE_STORAGE_CONNECTION_STRING;
  if (!cs) throw new Error("AZURE_STORAGE_CONNECTION_STRING is not configured.");
  return BlobServiceClient.fromConnectionString(cs).getContainerClient(BANK_CONTAINER);
}

function isOfficialSource(sourceId, examCode) {
  const s = String(sourceId || ""), e = String(examCode || "");
  return /^791381-20\d{2}/.test(s) || /^791367-20\d{2}/.test(s) || e === "791381" || e === "791367";
}
function sourceKind(sourceId) {
  if (isOfficialSource(sourceId)) return "official";
  if (String(sourceId) === MANUAL_SOURCE_ID) return "manual";
  return "import";
}

function presentationTypeFromBankQuestion(question) {
  if (question.type === "multipleChoice") return "multipleChoice";
  if (question.type === "multiField") {
    const fields = Array.isArray(question.fields) ? question.fields : [];
    const hasSelect = fields.some(f => String(f.kind || "").toLowerCase() === "select" || (Array.isArray(f.options) && f.options.length > 2));
    return hasSelect ? "wordBank" : "fillBlank";
  }
  return "open";
}
function presentationTypeToBankType(presentationType) {
  if (presentationType === "multipleChoice") return "multipleChoice";
  if (presentationType === "fillBlank" || presentationType === "wordBank") return "multiField";
  return "shortAnswer";
}

// One row per bank question: text/options/answer from the source document (authoritative content), topic /
// difficulty / section / reviewStatus from the index entry when present (what the builder selects on).
function toRow(question, indexEntry, sourceId) {
  const cls = question.classification || {};
  const idx = indexEntry || {};
  const official = isOfficialSource(sourceId, question.examCode);
  return {
    id: String(question.id),
    sourceId: String(sourceId),
    sourceKind: sourceKind(sourceId),
    official,
    questionNumber: String(question.questionNumber ?? idx.questionNumber ?? ""),
    section: String(idx.section || question.section || ""),
    topic: String(idx.topic || cls.topic || ""),
    difficulty: Number.isFinite(Number(idx.difficulty ?? cls.difficulty)) && (idx.difficulty ?? cls.difficulty) !== null ? Number(idx.difficulty ?? cls.difficulty) : null,
    difficultyLabel: String(idx.difficultyLabel || cls.difficultyLabel || ""),
    type: String(question.type || idx.type || ""),
    presentationType: presentationTypeFromBankQuestion(question),
    text: String(question.text || ""),
    options: (Array.isArray(question.options) ? question.options : []).map((o, i) => ({ value: String(o.value ?? i), text: String(o.text ?? o.label ?? "") })),
    fields: (Array.isArray(question.fields) ? question.fields : []).map(f => ({ id: String(f.id ?? ""), label: String(f.label ?? "") })),
    answer: question.answer && typeof question.answer === "object" ? question.answer : {},
    hasImage: (Array.isArray(question.assets) && question.assets.length > 0) || idx.hasImage === true,
    reviewStatus: String(idx.reviewStatus || question.reviewStatus || ""),
    createdAt: String(question.createdAt || ""),
    updatedAt: String(question.updatedAt || "")
  };
}

// Server-side validation of the editable payload. Same rules the builder's quality checks and the import gate
// apply: exact section, non-empty text, ≥ 2 options with a designated correct one for multiple choice, integer
// difficulty 1..5, known presentation type. Returns { ok, errors[] } — every error is an actionable Arabic message.
function validateQuestionInput(input) {
  const errors = [];
  const q = input && typeof input === "object" ? input : {};
  const text = String(q.text ?? "").trim();
  if (!text) errors.push("نص السؤال مطلوب.");
  else if (text.length > MAX_TEXT) errors.push("نص السؤال أطول من المسموح (" + MAX_TEXT + " حرفًا).");
  if (!VALID_SECTIONS.includes(q.section)) errors.push("القسم يجب أن يكون BASIC أو INFRASTRUCTURE.");
  const topic = String(q.topic ?? "").trim();
  if (!topic) errors.push("الموضوع مطلوب.");
  else if (topic.length > MAX_TOPIC) errors.push("الموضوع أطول من المسموح.");
  const difficulty = Number(q.difficulty);
  if (!Number.isInteger(difficulty) || difficulty < 1 || difficulty > 5) errors.push("الصعوبة يجب أن تكون رقمًا من 1 إلى 5.");
  if (!PRESENTATION_TYPES.includes(q.presentationType)) errors.push("نوع السؤال غير معروف.");
  const options = Array.isArray(q.options) ? q.options : [];
  const answer = q.answer && typeof q.answer === "object" ? q.answer : {};
  if (q.presentationType === "multipleChoice") {
    if (options.length < 2) errors.push("سؤال الاختيار من متعدد يحتاج خيارين على الأقل.");
    if (options.length > MAX_OPTIONS) errors.push("عدد الخيارات أكبر من المسموح.");
    options.forEach((o, i) => {
      const t = String(o?.text ?? "").trim();
      if (!t) errors.push("الخيار " + (i + 1) + " بلا نص.");
      else if (t.length > MAX_OPTION) errors.push("الخيار " + (i + 1) + " أطول من المسموح.");
    });
    const correct = String(answer.correctOptionValue ?? "").trim();
    if (!correct || !options.some((o, i) => String(o?.value ?? i) === correct)) errors.push("حدّد الإجابة الصحيحة من بين الخيارات.");
  } else {
    const values = Array.isArray(answer.values) ? answer.values : [];
    if (values.length > MAX_VALUES) errors.push("عدد الإجابات المقبولة أكبر من المسموح.");
    values.forEach((v, i) => { if (String(v ?? "").trim().length > MAX_VALUE) errors.push("الإجابة المقبولة " + (i + 1) + " أطول من المسموح."); });
  }
  return { ok: errors.length === 0, errors };
}

// Normalizes a validated payload into the canonical bank question fields (the SAME shape bank-import-action and
// build-bank-2025 write): options {value,label,text,textHtml,order}, answer {mode, values, ...}, classification.
function normalizeInput(q) {
  const presentationType = q.presentationType;
  const options = presentationType === "multipleChoice"
    ? q.options.map((o, i) => { const value = String(o.value ?? i).trim() || String(i); const text = String(o.text).trim(); return { value, label: text, text, textHtml: "", order: i }; })
    : [];
  let answer;
  if (presentationType === "multipleChoice") {
    const correct = String(q.answer.correctOptionValue).trim();
    const index = options.findIndex(o => o.value === correct);
    answer = { mode: "singleChoice", correctOptionValue: correct, correctOptionIndex: index, correctText: options[index]?.text || null, values: [correct] };
  } else {
    const values = (Array.isArray(q.answer?.values) ? q.answer.values : []).map(v => String(v).trim()).filter(Boolean);
    answer = values.length ? { mode: "anyAccepted", values } : { mode: "manual", values: [] };
  }
  return {
    section: q.section,
    type: presentationTypeToBankType(presentationType),
    text: String(q.text).trim(),
    textHtml: "",
    options,
    fields: [],
    answer,
    topic: String(q.topic).trim(),
    difficulty: Number(q.difficulty),
    flags: { hasOptions: options.length > 0, requiresManualReview: answer.mode === "manual" }
  };
}

function newQuestionId() {
  return MANUAL_SOURCE_ID + "-" + Date.now().toString(36) + "-" + crypto.randomBytes(3).toString("hex");
}
function toIndexEntry(question, sourceId, previous) {
  const cls = question.classification || {};
  return {
    ...(previous || {}),
    id: question.id, sourceId, sourcePriority: previous?.sourcePriority ?? 0,
    questionNumber: question.questionNumber || "", section: question.section, type: question.type, originalType: previous?.originalType || question.type,
    topic: cls.topic || "UNKNOWN", difficulty: cls.difficulty ?? null, familyKey: cls.familyKey || "",
    hasImage: (question.assets || []).length > 0, assetCount: (question.assets || []).length, reviewStatus: question.reviewStatus,
    secondaryTopics: cls.secondaryTopics || [], difficultyLabel: cls.difficultyLabel || "", hasCLI: previous?.hasCLI === true, requiresCalculation: previous?.requiresCalculation === true,
    needsReview: question.flags?.requiresManualReview === true, classificationConfidence: cls.difficultyConfidence ?? null
  };
}
const bad = (status, error, extra) => ({ status, jsonBody: { ok: false, error, ...(extra || {}) } });

async function handler(request, deps = {}, obs = null) {
  const authFn = deps.requireBuilderAuth || requireBuilderAuth;
  const getBank = deps.getBankContainer || getBankContainer;
  const dl = deps.downloadJsonOrNull || downloadJsonOrNull;
  const ls = deps.listJson || listJson;
  const mutate = deps.mutateJsonWithRetry || mutateJsonWithRetry;
  const conflict = deps.isConcurrencyConflict || isConcurrencyConflict;
  const audit = deps.recordAuditEvent || recordAuditEvent;
  const getPlatform = deps.getPlatformContainer || getPlatformContainer;
  const now = deps.now || (() => new Date().toISOString());
  const makeId = deps.newQuestionId || newQuestionId;
  try {
    const auth = authFn(request);
    if (!auth.ok) return auth.response;
    const bank = getBank();
    const actor = String(auth.user?.sub || auth.user?.userCode || "teacher");
    const readIndex = async () => { const index = await dl(bank, INDEX_BLOB); return Array.isArray(index?.questions) ? index.questions : []; };

    if (request.method === "GET") {
      const [entries, sources] = await Promise.all([readIndex(), ls(bank, SOURCES_PREFIX)]);
      const byId = new Map(entries.map(e => [String(e.id), e]));
      const rows = [];
      for (const document of sources) {
        for (const question of Array.isArray(document?.questions) ? document.questions : []) {
          if (!question?.id) continue;
          const sourceId = question.sourceId || byId.get(String(question.id))?.sourceId || "";
          rows.push(toRow(question, byId.get(String(question.id)), sourceId));
        }
      }
      rows.sort((a, b) => (b.updatedAt || b.createdAt || "").localeCompare(a.updatedAt || a.createdAt || "") || a.id.localeCompare(b.id));
      obs?.logInfo?.("bank.questions.listed", { rows: rows.length, sources: sources.length });
      return { status: 200, jsonBody: { ok: true, questions: rows, sections: VALID_SECTIONS, presentationTypes: PRESENTATION_TYPES } };
    }

    let body = {};
    try { body = await request.json(); } catch { body = {}; }
    const action = String(body?.action || "").trim().toLowerCase();
    if (!["create", "update", "delete"].includes(action)) return bad(400, "الإجراء غير معروف (create / update / delete).");

    const locate = async id => {
      if (!ID_PATTERN.test(id)) return { error: bad(400, "معرّف السؤال غير صالح.") };
      const entry = (await readIndex()).find(e => String(e.id) === id);
      let sourceId = entry?.sourceId ? String(entry.sourceId) : "";
      if (!sourceId) {
        // Index and source documents can drift (a source committed before its index write completed): fall back
        // to scanning the source documents once instead of reporting a question that exists as missing.
        for (const document of await ls(bank, SOURCES_PREFIX)) {
          const hit = (document?.questions || []).find(q => String(q?.id) === id);
          if (hit) { sourceId = String(hit.sourceId || ""); break; }
        }
      }
      if (!sourceId) return { error: bad(404, "السؤال غير موجود في بنك الأسئلة.") };
      if (isOfficialSource(sourceId)) return { error: bad(403, "أسئلة البنك الرسمي للقراءة فقط ولا يمكن تعديلها أو حذفها من هنا.") };
      return { sourceId, entry };
    };

    if (action === "create") {
      const check = validateQuestionInput(body?.question);
      if (!check.ok) return bad(400, check.errors[0], { errors: check.errors });
      const n = normalizeInput(body.question);
      const stamp = now();
      const question = {
        id: makeId(), sourceId: MANUAL_SOURCE_ID, sourceQuestionId: "", questionNumber: "",
        section: n.section, type: n.type, text: n.text, textHtml: n.textHtml, options: n.options, fields: n.fields, parts: [], answer: n.answer, assets: [],
        flags: { hasImage: false, hasOptions: n.flags.hasOptions, isChild: false, requiresManualReview: n.flags.requiresManualReview },
        classification: { topic: n.topic, secondaryTopics: [], difficulty: n.difficulty, difficultyLabel: "", difficultyReason: "teacher-entered in Exam Bank management", difficultyConfidence: null, familyKey: null, status: "classified" },
        reviewStatus: "classified", createdBy: actor, createdAt: stamp, updatedAt: stamp
      };
      question.sourceQuestionId = question.id;
      await mutate(bank, SOURCES_PREFIX + MANUAL_SOURCE_ID + ".json", current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        if (questions.some(q => String(q?.id) === question.id)) throw Object.assign(new Error("duplicate id"), { code: "DUPLICATE_ID" });
        return { ...(current || {}), sourceId: MANUAL_SOURCE_ID, questions: [...questions, question] };
      });
      let entry;
      await mutate(bank, INDEX_BLOB, current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        entry = toIndexEntry(question, MANUAL_SOURCE_ID, null);
        return { ...(current || {}), questions: [...questions.filter(e => String(e?.id) !== question.id), entry] };
      });
      await audit(getPlatform(), { actor, action: "bank.question.create", targetType: "bankQuestion", targetId: question.id, details: { sourceId: MANUAL_SOURCE_ID, section: n.section } });
      return { status: 200, jsonBody: { ok: true, question: toRow(question, entry, MANUAL_SOURCE_ID) } };
    }

    const id = String(body?.id || "").trim();
    const found = await locate(id);
    if (found.error) return found.error;

    if (action === "update") {
      const check = validateQuestionInput(body?.question);
      if (!check.ok) return bad(400, check.errors[0], { errors: check.errors });
      const n = normalizeInput(body.question);
      const stamp = now();
      let updated = null;
      await mutate(bank, SOURCES_PREFIX + found.sourceId + ".json", current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const i = questions.findIndex(q => String(q?.id) === id);
        if (i < 0) throw Object.assign(new Error("missing"), { code: "NOT_FOUND" });
        const previous = questions[i];
        updated = {
          ...previous, section: n.section, type: n.type, text: n.text, textHtml: n.textHtml, options: n.options, answer: n.answer,
          flags: { ...(previous.flags || {}), hasOptions: n.flags.hasOptions, requiresManualReview: n.flags.requiresManualReview },
          classification: { ...(previous.classification || {}), topic: n.topic, difficulty: n.difficulty, status: "classified" },
          reviewStatus: "classified", updatedBy: actor, updatedAt: stamp
        };
        return { ...current, questions: questions.map((q, k) => (k === i ? updated : q)) };
      });
      let entry;
      await mutate(bank, INDEX_BLOB, current => {
        const questions = Array.isArray(current?.questions) ? current.questions : [];
        const previous = questions.find(e => String(e?.id) === id) || null;
        entry = toIndexEntry(updated, found.sourceId, previous);
        return { ...(current || {}), questions: [...questions.filter(e => String(e?.id) !== id), entry] };
      });
      await audit(getPlatform(), { actor, action: "bank.question.update", targetType: "bankQuestion", targetId: id, details: { sourceId: found.sourceId, section: n.section } });
      return { status: 200, jsonBody: { ok: true, question: toRow(updated, entry, found.sourceId) } };
    }

    // delete — the question leaves the source document and the index; image assets (if any) stay in the assets
    // container (no cascade), saved exams keep their own snapshots.
    let removed = false;
    await mutate(bank, SOURCES_PREFIX + found.sourceId + ".json", current => {
      const questions = Array.isArray(current?.questions) ? current.questions : [];
      const remaining = questions.filter(q => String(q?.id) !== id);
      removed = remaining.length !== questions.length;
      if (!removed) throw Object.assign(new Error("missing"), { code: "NOT_FOUND" });
      return { ...current, questions: remaining };
    });
    await mutate(bank, INDEX_BLOB, current => {
      const questions = Array.isArray(current?.questions) ? current.questions : [];
      return { ...(current || {}), questions: questions.filter(e => String(e?.id) !== id) };
    });
    await audit(getPlatform(), { actor, action: "bank.question.delete", targetType: "bankQuestion", targetId: id, details: { sourceId: found.sourceId } });
    return { status: 200, jsonBody: { ok: true, deleted: true, id } };
  } catch (e) {
    if (e?.code === "NOT_FOUND") return bad(404, "السؤال غير موجود في بنك الأسئلة.");
    if (e?.code === "DUPLICATE_ID") return bad(409, "تعذر إنشاء السؤال: تعارض في المعرّف، أعد المحاولة.");
    if (conflict(e) || e?.name === "StorageConflictError") return bad(409, "تعذر الحفظ بسبب تعديل متزامن على بنك الأسئلة، أعد المحاولة.");
    obs?.logError?.("bank.questions.failed", e, { method: request.method });
    return bad(500, "تعذر تنفيذ العملية على بنك الأسئلة حاليًا.");
  }
}

app.http("bankQuestions", { methods: ["GET", "POST"], authLevel: "anonymous", route: "bank-questions", handler: withObservability("bank-questions", handler) });
module.exports = { handler, validateQuestionInput, normalizeInput, toRow, isOfficialSource, presentationTypeFromBankQuestion, MANUAL_SOURCE_ID, INDEX_BLOB, SOURCES_PREFIX };
