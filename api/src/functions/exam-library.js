const { app } = require("@azure/functions");
const { withObservability } = require("../lib/observability");
const { requireTeacherSession } = require("../lib/teacher-session");
const { requireCapability } = require("../lib/access/require-capability");   // Tadris+ P3-B
const { deliveryCopy } = require("../lib/content-assets");   // Tadris+ P5-C
const { teacherLibraryFilter, importedLibraryFilter, libraryAccessUnavailable } = require("../lib/access/library-access");   // Tadris+ P6-D, P6-E
const crypto = require("crypto");
// The exam library is read-only global system data, so it ships bundled with the app (versioned in
// the repo under api/src/data/exam-library, generated by scripts/build-791381-library.cjs) and is
// read straight off disk - same pattern as config/topics.json. No Azure Blob, no upload step: git
// -> deploy -> library available. The reader lives in lib/exam-library-store.js (shared with the
// student learning-training endpoint); if the library later becomes editable from a SuperAdmin
// panel, that single reader can be swapped to Blob without touching any caller.
//
// Phase L.7 — operations: the store reads each file once per process (cached, frozen); the endpoint runs under the shared
// observability wrapper (request id, duration, status class, redacted error events) and answers with a strong ETag and
// `private, no-cache` — a teacher's browser keeps the catalog / an item and revalidates it, and a 304 is answered only after
// the builder check passed. The library carries answer keys, so it is never cacheable by a shared cache.
const { VALID_ID, libraryItemEntry } = require("../lib/exam-library-store");
const { IMPORTED_ID, ImportedLibraryError, resolveLibraryItemEntry, resolveLibraryCatalogEntry } = require("../lib/exam-library-imported");   // Tadris+ P6-E
const { authorize } = require("../lib/access/authorize");
const { sanitizeExamForStudent } = require("../lib/student-exam-sanitize");
const { getContainer } = require("../lib/platform-storage");

// Tadris+ P6-A (risk S2, owner decision D8) — the library carries ANSWER KEYS. The catalog needs examLibrary.item.view; one item
// needs examLibrary.item.preview or examLibrary.item.viewKeys; the KEYS are sent only with examLibrary.item.viewKeys — otherwise
// the item is the same exam sanitized exactly like a student's view (no correct answers, hints or explanations), marked
// `answerKeys: false`, with its own ETag (a browser never mixes the two). Evaluated like every capability: a managed session while
// enforcing (legacy-full identities and the other modes: unchanged). Assigning a library item never needs the keys: the server
// builds the assignment from its own frozen copy (manage-assignments `libraryRef`).
const keylessCache = new Map();
function keylessEntry(entry) {
  const hit = keylessCache.get(entry.etag);
  if (hit) return hit;
  const value = Object.freeze({ ...entry.value, examSnapshot: sanitizeExamForStudent(entry.value.examSnapshot), answerKeys: false });
  const out = Object.freeze({ value, etag: String(entry.etag).replace(/"$/, "-nokeys\"") });
  keylessCache.set(entry.etag, out);
  return out;
}

/** The catalog narrowed to a teacher's bank, with an ETag of exactly what it lists. */
function bankCatalog(entry, bank) {
  const value = entry.value.filter(item => item && bank(item.libraryItemId));
  if (value.length === entry.value.length) return entry;
  const ids = value.map(item => item.libraryItemId).join(",");
  return { value, etag: "\"" + crypto.createHash("sha256").update(String(entry.etag) + "|" + ids).digest("base64url").slice(0, 22) + "\"" };
}

const CACHE_HEADERS = { "Cache-Control": "private, no-cache", Vary: "Authorization, x-builder-token" };
const notModified = (request, etag) => {
  const ifNoneMatch = String(request.headers?.get?.("if-none-match") || "");
  return !!ifNoneMatch && ifNoneMatch.split(",").map(t => t.trim()).includes(etag);
};

async function handler(request, deps = {}, obs = null) {
  try {
    const auth = (await requireTeacherSession(request, deps));
    if (!auth.ok) return auth.response;
    const capabilityDenial = await requireCapability(auth, "exam-library.js", "*", deps, obs);   // Tadris+ P3-B
    if (capabilityDenial) return capabilityDenial;

    const id = String(request.params?.id || "").trim();
    // Small metadata-only catalog (no examSnapshot) when no id is given; the frontend decides how to present each item's
    // publishable flag. Full item JSON is fetched separately only when one is selected.
    if (id && !VALID_ID.test(id)) return { status: 400, jsonBody: { ok: false, error: "معرّف غير صالح." } };
    // Tadris+ P6-E — the library is the bundled exams AND the exams the owner imported (lib/exam-library-imported.js): a bundled
    // item never touches storage; the catalog and an imported item read the imported index (unreadable / not understood → 503).
    const containerOf = () => deps.container || (deps.getContainer || getContainer)();
    let entry;
    try {
      if (id) entry = libraryItemEntry(id) || (IMPORTED_ID.test(id) ? await resolveLibraryItemEntry(containerOf(), id, deps) : null);
      else entry = await resolveLibraryCatalogEntry(containerOf(), deps);
    } catch (e) { if (e instanceof ImportedLibraryError) return libraryAccessUnavailable(); throw e; }
    if (!entry) return { status: 404, jsonBody: { ok: false, error: "العنصر غير موجود في المكتبة." } };
    // Tadris+ P6-D — the teacher's own bank: the catalog lists only its exams (its own ETag); another exam is answered exactly like
    // a missing one. No narrowing for identities that predate the console, or before enforcement (library-access.js).
    let bank = null;
    if (auth.user && auth.user.am === "managed") {
      try { bank = await teacherLibraryFilter(deps.container || (deps.getContainer || getContainer)(), auth.user, deps); } catch { return libraryAccessUnavailable(); }
    }
    // Tadris+ P6-E — an imported exam follows its audience for every session, even where the bundled library is not narrowed.
    if (!bank && (id ? IMPORTED_ID.test(id) : entry.value.some(i => i && IMPORTED_ID.test(String(i.libraryItemId))))) {
      let seen;
      try { seen = await importedLibraryFilter(containerOf(), auth.user, deps); } catch { return libraryAccessUnavailable(); }
      bank = itemId => !IMPORTED_ID.test(String(itemId)) || seen(itemId);
    }
    if (bank && id && !bank(id)) return { status: 404, jsonBody: { ok: false, error: "العنصر غير موجود في المكتبة." } };
    if (bank && !id) entry = bankCatalog(entry, bank);
    if (id && auth.user && auth.user.am === "managed") {
      const authDeps = { ...deps, container: deps.container || (deps.getContainer || getContainer)() };
      const item = await authorize(auth.user, ["examLibrary.item.preview", "examLibrary.item.viewKeys"], authDeps, obs);
      if (!item.allowed) return item.response;
      const keys = await authorize(auth.user, "examLibrary.item.viewKeys", authDeps, obs);
      if (!keys.allowed) entry = keylessEntry(entry);
    }
    // Tadris+ P5-C (S7, D10): an item's question images are delivered as this window's signed URLs (its own ETag per window).
    if (id) entry = deliveryCopy(entry.value, entry.etag, (deps.nowMs || Date.now)());
    const headers = { ...CACHE_HEADERS, ETag: entry.etag };
    if (notModified(request, entry.etag)) return { status: 304, headers };
    return { status: 200, headers, jsonBody: id ? { ok: true, item: entry.value } : { ok: true, catalog: entry.value } };
  } catch (e) {
    obs?.logError?.("exam.library.error", e);
    return { status: 500, jsonBody: { ok: false, error: "تعذر تحميل مكتبة الامتحانات حاليًا." } };
  }
}

const observed = withObservability("exam-library", handler);
app.http("examLibrary", { methods: ["GET"], authLevel: "anonymous", route: "exam-library/{id?}", handler: observed });

module.exports = { handler, observed };
