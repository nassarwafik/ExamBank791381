const { canonicalizeExamContent } = require_("../../src/lib/exam-canonical.js");
const { normalizeDraftAnswers } = require_("../../src/lib/draft-answers.js");
const { scoreAutomatonDesign } = require_("../../src/lib/automaton-design-grading.js");
const { evaluateAutomatonDesign } = require_("../../src/lib/learning-automaton-design.js");
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const load = () => JSON.parse(fs.readFileSync(path.join(repo, AUTOMATON_DESIGN_ACCEPTANCE_PATH), "utf8"));
const qs = e => e.sections.flatMap(s => s.questions);
const configsOf = e => Object.fromEntries(qs(e).filter(q => q.automatonDesign).map(q => [q.examQuestionId, q.automatonDesign]));
const STUDENTS = { "ad-perfect": "طالب مثالي", "ad-partial": "طالب جزئي", "ad-blank": "طالب لم يجب", "ad-attacker": "طالب مهاجم" };

const m = (states, start, accept, transitions) => ({ states, start, accept, transitions: transitions.map(t => t.split(" ")) });
const ans = machine => ({ kind: "automatonDesign", machine });
const PERFECT = {
  d1: ans(m(["s", "t"], "s", ["t"], ["s 0 s", "s 1 t", "t 0 s", "t 1 t"])),                                    // the reference renamed
  d2: ans(m(["e", "o"], "e", ["e"], ["e b e", "e a o", "o b o", "o a e"])),                                    // arrows in another order
  n1: ans(m(["q0", "q1", "q2"], "q0", ["q2"], ["q0 a q1", "q0 b q0", "q1 a q1", "q1 b q2", "q2 a q1", "q2 b q0"])),   // a DFA (allowed in an NFA question)
  n2: ans(m(["p", "r", "f", "g"], "p", ["g"], ["p a p", "p b p", "p a r", "r a f", "f ε g", "g a g", "g b g"])),   // an ε arrow
  c1: A.choice(0),
};
// d1 incomplete (no arrow from t with 0 — the question asks a COMPLETE automaton) · n1 accepts «ends with b» (the first different word: b)
// · c1 a wrong option. d2 and n2 are right.
const PARTIAL = {
  ...PERFECT,
  d1: ans(m(["s", "t"], "s", ["t"], ["s 0 s", "s 1 t", "t 1 t"])),
  n1: ans(m(["q0", "q1"], "q0", ["q1"], ["q0 a q0", "q0 b q0", "q0 b q1"])),
  c1: A.choice(1),
};
const LEDGER = {
  PERFECT: { d1: [5, 0], d2: [5, 0], n1: [6, 0], n2: [4, 0], c1: [2, 0] },
  PARTIAL: { d1: [0, 0], d2: [5, 0], n1: [0, 0], n2: [4, 0], c1: [0, 0] },
};
const TOTAL = { PERFECT: 22, PARTIAL: 9 };
// ATTACKER — a self-graded answer (extra fields), a prototype state, an oversized machine, an automaton answer on the multiple-choice
// question and on a question that does not exist are refused at ingest; a machine that merely BREAKS a rule of its question (n2: 6 states,
// the limit is 4) is a real answer: kept, and judged wrong.
const big = Array.from({ length: 201 }, () => "q0 a q0");
const ATTACKER = {
  d1: { ...PERFECT.d1, score: 5, correct: true },
  d2: ans(m(["__proto__"], "__proto__", [], [])),
  n1: ans(m(["q0"], "q0", ["q0"], big)),
  n2: ans(m(["a1", "a2", "a3", "a4", "a5", "a6"], "a1", ["a1"], ["a1 a a2"])),
  c1: PERFECT.d1,
  zz: PERFECT.d1,
};
const ATTACKER_REFUSED = [["c1", "AUTOMATON_QUESTION_MISMATCH"], ["d1", "AUTOMATON_ANSWER_INVALID"], ["d2", "AUTOMATON_ANSWER_INVALID"], ["n1", "AUTOMATON_ANSWER_INVALID"], ["zz", "AUTOMATON_QUESTION_MISMATCH"]];

describe("A8 authoring: the fixture is a real, finalizable exam", () => {
  it("schemaVersion 2, three sections (22 marks), four automatonDesign questions + one multiple choice, each valid", () => {
    const e = load();
    expect([e.schemaVersion, e.examId, e.sections.map(s => s.id)]).toEqual([2, "EXAMBANK-A8-AUTOMATON-DESIGN", ["sec-dfa", "sec-nfa", "sec-mixed"]]);
    const s = examOfficialStats(e);
    expect([s.totalMarks, ...s.sections.map(x => x.totalMarks)]).toEqual([22, 10, 10, 2]);
    expect(qs(e).map(q => q.presentationType)).toEqual([...Array(4).fill("automatonDesign"), "multipleChoice"]);
    for (const q of qs(e).filter(x => x.automatonDesign)) expect(validateAutomatonDesignQuestion(q), q.examQuestionId).toEqual([]);
    expect(evaluateExamFinalization(e).blockers.map(b => b.message)).toEqual([]);
  });
  it("import / export is EXACT: import → canonical save → export → import keeps every config and reference", () => {
    const e = load();
    const imp = parseStructuredExamJson(JSON.stringify(e), "ExamBank_A8_Automaton_Design_Acceptance.json");
    expect([imp.canOpen, imp.parseErrors, imp.validationErrors.filter(i => i.severity === "error")]).toEqual([true, [], []]);
    expect(qs(imp.exam)).toEqual(qs(e));
    const saved = toSavedStructuredExam(imp.exam);
    expect(configsOf(saved)).toEqual(configsOf(e));
    const again = parseStructuredExamJson(JSON.stringify(saved), "re-export.json");
    expect(configsOf(again.exam)).toEqual(configsOf(e));
    expect(qs(again.exam).map(q => q.answer)).toEqual(qs(e).map(q => q.answer));
    expect(configsOf(canonicalizeExamContent(e))).toEqual(configsOf(e));
  });
  it("finalization refuses a question without a reference, a reference that contradicts the example words, or rules that do not read", () => {
    const tamper = (id, mutate) => { const e = load(); mutate(qs(e).find(q => q.examQuestionId === id)); return evaluateExamFinalization(e).blockers.length; };
    expect(tamper("d1", q => { q.answer = {}; })).toBeGreaterThan(0);
    expect(tamper("d1", q => { q.answer.reference.accept = ["q0"]; })).toBeGreaterThan(0);              // now rejects «1», an accepted example
    expect(tamper("n1", q => { q.automatonDesign.machine = "PDA"; })).toBeGreaterThan(0);
    expect(tamper("d2", q => { q.automatonDesign.maxStates = 13; })).toBeGreaterThan(0);
    expect(tamper("d2", q => { q.answer.reference.transitions.push(["q0", "c", "q0"]); })).toBeGreaterThan(0);
  });
  it("a \"first N answered\" section counts an automaton answer as answered — the empty start state alone is not an answer", () => {
    const e = load();
    e.sections = [{ ...e.sections[0], gradingPolicy: "firstNAnswered", requiredAnswers: 1 }];
    const blank = ans(m(["q0"], "q0", [], []));
    const r = gradeExam(e, { d1: blank, d2: PERFECT.d2 });
    expect([r.score, r.totalMarks, r.questions.filter(q => q.countedMaxMarks > 0).map(q => q.questionId)]).toEqual([5, 5, ["d2"]]);
  });
  it("the sanitizer REBUILDS the rules: a field smuggled into them withholds them whole (the student never sees it)", () => {
    const e = load();
    qs(e)[0].automatonDesign.hint = "الحل: حالتان";
    const p = sanitizeExamForStudent(e);
    expect(qs(p)[0].automatonDesign).toBeUndefined();
    expect(JSON.stringify(p)).not.toContain("الحل: حالتان");
    expect(configsOf(p).d2).toEqual(configsOf(load()).d2);
  });
  it("the student projection keeps the rules exactly and never the reference", () => {
    const e = load(), p = sanitizeExamForStudent(e);
    expect(configsOf(p)).toEqual(configsOf(e));
    const json = JSON.stringify(p);
    expect(json).not.toMatch(/"reference"|"transitions"/);
    for (const q of qs(p).filter(x => x.automatonDesign)) expect(q.answer ?? {}).toEqual({});
    expect(scanProjection(p, { secrets: ["\"reference\""] })).toEqual([]);
  });
});

describe("A8 the grade is the language, by the book exercises' judge", () => {
  const book = () => {
    const out = [];
    const walk = v => { if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === "object") { if (v.simulationType === "automaton-design" && v.config) out.push(v); else Object.values(v).forEach(walk); } };
    for (const f of fs.readdirSync(path.join(repo, "src/learning/content/899271/modules"))) {
      const src = fs.readFileSync(path.join(repo, "src/learning/content/899271/modules", f), "utf8");
      const json = src.slice(src.indexOf("{", src.indexOf("= ")), src.lastIndexOf("}") + 1);
      try { walk(JSON.parse(json)); } catch { /* a module that is not a plain object literal holds no exercise */ }
    }
    return out;
  };
  it("the book's 10 «صمّم الآلة» exercises, as exam questions: valid; a reference answering its own question is graded as the judge decides", () => {
    const blocks = book();
    expect(blocks.length).toBe(10);
    const breaksOwnRules = [];
    for (const b of blocks) {
      const t = b.config.task;
      const rules = { v: 1, machine: t.machine, alphabet: t.alphabet, maxStates: t.maxStates ?? 12, ...(t.complete ? { complete: true } : {}) };
      const question = { presentationType: "automatonDesign", questionTypeVersion: 1, automatonDesign: { ...rules, ...(t.examples ? { examples: { accept: t.examples.accept ?? [], reject: t.examples.reject ?? [] } } : {}) }, answer: { reference: b.config.reference } };
      expect(validateAutomatonDesignQuestion(question), b.id).toEqual([]);       // the book's example words agree with its reference
      // the reference may be an NFA for a DFA question (the same language): as a STUDENT's answer it then breaks a rule — exactly the judge's verdict
      const judge = evaluateAutomatonDesign({ kind: "automaton-design", rules: { machine: t.machine, alphabet: t.alphabet, maxStates: rules.maxStates, complete: !!t.complete }, reference: b.config.reference }, { kind: "automaton-design", machine: b.config.reference });
      const exam = scoreAutomatonDesign({ config: question.automatonDesign, answerKey: question.answer, response: ans(b.config.reference), maxMarks: 7 });
      expect([exam.correct, exam.score, exam.issue ?? null], b.id).toEqual([judge.correct, judge.correct ? 7 : 0, judge.issue ?? null]);
      if (!judge.correct) breaksOwnRules.push(b.id + ":" + judge.issue.code);
      // under the non-deterministic rules every reference is its own language: full marks
      expect(scoreAutomatonDesign({ config: { v: 1, machine: "NFA", alphabet: t.alphabet, maxStates: 12 }, answerKey: question.answer, response: ans(b.config.reference), maxMarks: 7 }), b.id).toEqual({ score: 7, correct: true, manualReview: false });
    }
    expect(breaksOwnRules).toEqual(["m03-l05-p01-b04:two-arrows", "m03-l05-p01-b05:two-arrows"]);   // the book's two «المهمة الإضافية» references are NFAs for a DFA question
  });
  it("parity with the practice judge: every pair of book references (same alphabet) is graded exactly as the judge decides", () => {
    const blocks = book();
    let pairs = 0;
    for (const a of blocks) for (const b of blocks) {
      if (a.config.task.alphabet.join() !== b.config.task.alphabet.join()) continue;
      const t = b.config.task, rules = { machine: "NFA", alphabet: t.alphabet, maxStates: 12, complete: false };
      const judge = evaluateAutomatonDesign({ kind: "automaton-design", rules, reference: b.config.reference }, { kind: "automaton-design", machine: a.config.reference });
      const exam = scoreAutomatonDesign({ config: { v: 1, machine: "NFA", alphabet: t.alphabet, maxStates: 12 }, answerKey: { reference: b.config.reference }, response: ans(a.config.reference), maxMarks: 3 });
      expect([exam.correct, exam.score, exam.counterexample ?? null], a.id + " vs " + b.id).toEqual([judge.correct, judge.correct ? 3 : 0, judge.counterexample ?? null]);
      pairs++;
    }
    expect(pairs).toBeGreaterThan(10);
  });
  it("a judge that cannot decide (its bounds reached) sends the answer to teacher review — never a silent zero", () => {
    const judge = require_("../../src/lib/learning-automaton-design.js");
    const gradingPath = require_.resolve("../../src/lib/automaton-design-grading.js");
    const real = judge.evaluateAutomatonDesign;
    try {
      judge.evaluateAutomatonDesign = () => ({ status: "unavailable" });
      delete require_.cache[gradingPath];
      const { scoreAutomatonDesign: undecided } = require_(gradingPath);
      const q = qs(load())[0];
      expect(undecided({ config: q.automatonDesign, answerKey: q.answer, response: PERFECT.d1, maxMarks: 5 })).toEqual({ score: 0, correct: false, manualReview: true });
    } finally {
      judge.evaluateAutomatonDesign = real;
      delete require_.cache[gradingPath];
    }
  });
  it("the separating word and the broken rule are kept beside the score; the reference states are never in the result", () => {
    const e = load(), q = id => qs(e).find(x => x.examQuestionId === id);
    const s = (id, answer) => scoreAutomatonDesign({ config: q(id).automatonDesign, answerKey: q(id).answer, response: answer, maxMarks: q(id).marks });
    expect(s("n1", PARTIAL.n1)).toEqual({ score: 0, correct: false, manualReview: false, counterexample: { word: "b", shouldAccept: false } });
    expect(s("d1", PARTIAL.d1)).toEqual({ score: 0, correct: false, manualReview: false, issue: { code: "incomplete", state: "t", symbol: "0" } });
    expect(s("n2", ATTACKER.n2)).toEqual({ score: 0, correct: false, manualReview: false, issue: { code: "too-many-states", max: 4 } });
    expect(s("d2", undefined)).toEqual({ score: 0, correct: false, manualReview: false });
  });
});

describe("A8 full platform lifecycle", () => {
  let p, aid, published;
  const runs = {};
  beforeAll(async () => {
    p = createPlatform({ students: STUDENTS });
    published = await publishAndAssign(p, load());
    aid = published.aid;
    runs.PERFECT = await takeExam(p, aid, "ad-perfect", PERFECT, { chunks: 3 });
    runs.PARTIAL = await takeExam(p, aid, "ad-partial", PARTIAL);
  }, 120000);

  it("save → load → governance → publish → assignment keep every config and reference byte-for-byte", () => {
    const e = load();
    expect(published.pub.ok).toBe(true);
    expect(configsOf(published.loaded)).toEqual(configsOf(e));
    expect(configsOf(p.assignmentOf(aid).examSnapshot)).toEqual(configsOf(e));
    expect(qs(p.assignmentOf(aid).examSnapshot).map(q => q.answer)).toEqual(qs(e).map(q => q.answer));
  });
  it("delivery: the student receives the rules exactly, pre-start hides the body, the reference never leaves the server", () => {
    const e = load();
    for (const [name, r] of Object.entries(runs)) {
      expect(r.preStart.status, name).toBe(200);
      expect(JSON.stringify(r.preStart.jsonBody), name).not.toContain("automatonDesign\":{");
      expect(configsOf(r.delivery.jsonBody.assignment.exam), name).toEqual(configsOf(e));
      expect(JSON.stringify(r.delivery.jsonBody), name).not.toMatch(/"reference"/);
      for (const ref of Object.values(REFERENCES_A8)) expect(JSON.stringify(r.delivery.jsonBody), name).not.toContain(JSON.stringify(ref.transitions));
    }
  });
  it("autosave / restore of the machines is exact; submit is idempotent; ledgers = hand-derived", () => {
    for (const [name, r] of Object.entries(runs)) {
      for (const x of r.restores) expect(x.restored, name).toEqual(x.expected.answers);
      expect([r.submit.status, r.duplicateSubmit.status], name).toEqual([200, 409]);
      expect(ledgerOf(r.attempt).questions, name).toEqual(LEDGER[name]);
      expect([r.attempt.score, r.attempt.totalMarks, r.attempt.finalized], name).toEqual([TOTAL[name], 22, true]);
      expect(attemptInvariants(r.attempt, 22), name).toEqual([]);
    }
    expect(runs.PERFECT.attempt.answers.n2).toEqual(PERFECT.n2);
  });
  it("a blank submission scores 0 and is final (never a review)", async () => {
    const s = p.student("ad-blank");
    await s.start(aid);
    expect((await s.submit(aid, {})).status).toBe(200);
    expect(ledgerOf(s.attempt(aid)).questions).toEqual(Object.fromEntries(Object.keys(LEDGER.PERFECT).map(id => [id, [0, 0]])));
    expect([s.attempt(aid).score, s.attempt(aid).manualReviewMarks, s.attempt(aid).finalized]).toEqual([0, 0, true]);
  });
  it("ATTACKER: forged answers are refused at ingest with their codes; a machine that only breaks a rule is kept and judged wrong", async () => {
    const snapshot = p.assignmentOf(aid).examSnapshot;
    const n = normalizeDraftAnswers(ATTACKER, snapshot);
    expect(n.rejected.map(r => [r.id, r.code]).sort()).toEqual([...ATTACKER_REFUSED].sort());
    expect(Object.keys(n.answers)).toEqual(["n2"]);
    const s = p.student("ad-attacker");
    expect((await s.start(aid)).status).toBe(200);
    expect((await s.submit(aid, ATTACKER)).status).toBe(200);
    const att = s.attempt(aid);
    expect(Object.keys(att.answers)).toEqual(["n2"]);
    expect([att.score, att.manualReviewMarks, att.finalized]).toEqual([0, 0, true]);
    expect(attemptInvariants(att, 22)).toEqual([]);
    expect(JSON.stringify(att)).not.toMatch(/"score":5,"correct":true|__proto__/);
  });
  it("grading is decided by the server only and is repeatable", () => {
    const snapshot = p.assignmentOf(aid).examSnapshot;
    for (const [name, r] of Object.entries(runs)) expect([gradeExam(snapshot, r.attempt.answers).score, gradeExam(snapshot, r.attempt.answers).score], name).toEqual([TOTAL[name], TOTAL[name]]);
  });
  it("FAIL CLOSED on the published snapshot: rules or a reference that can no longer be read go to teacher review — never a mark, never a silent zero", () => {
    const snapshot = structuredClone(p.assignmentOf(aid).examSnapshot);
    const q = id => qs(snapshot).find(x => x.examQuestionId === id);
    q("d2").automatonDesign.machine = "TM";                      // a machine type this application does not grade
    q("n1").answer.reference.start = "nowhere";                   // a reference that cannot be read
    const r = gradeExam(snapshot, runs.PERFECT.attempt.answers);
    const row = id => r.questions.find(x => x.questionId === id);
    expect([row("d2").manualReview, row("d2").score, row("n1").manualReview, row("n1").score]).toEqual([true, 0, true, 0]);
    expect(["d1", "n2", "c1"].map(id => row(id).manualReview)).toEqual([false, false, false]);
    expect([r.score, r.manualReviewMarks, r.finalized]).toEqual([22 - 5 - 6, 5 + 6, false]);
  });
  it("teacher review: the question carries its rules, the reference and the stored machine; the review saves", async () => {
    const rv = await p.teacher.reviewGet(aid, "ad-partial");
    expect(rv.status).toBe(200);
    const byId = Object.fromEntries(rv.jsonBody.questions.map(q => [q.questionId, q]));
    for (const [id, [auto]] of Object.entries(LEDGER.PARTIAL)) expect(byId[id].autoGrade.score, id).toBe(auto);
    expect([byId.n1.type, byId.n1.expectedAnswer, byId.n1.studentAnswer]).toEqual(["automatonDesign", { reference: REFERENCES_A8.endsWithAb }, PARTIAL.n1]);
    const saved = await p.teacher.saveReview(aid, "ad-partial", {}, 1, "مراجعة أسئلة تصميم الأوتومات");
    expect([saved.status, saved.jsonBody.result.score, saved.jsonBody.result.finalized]).toEqual([200, 9, true]);
  });
});
