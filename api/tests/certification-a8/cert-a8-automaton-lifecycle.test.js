// scripts/generate-automaton-design-a8-fixture.mjs): an Arabic exam with two deterministic questions (one asks a COMPLETE automaton), two
// non-deterministic ones and an ordinary multiple-choice question — 22 marks. Driven through the REAL platform: import / canonical save /
// export / re-import, finalization, save → load → governance → publish → assignment, sanitized delivery (rules exact, NO reference),
// autosave / restore, idempotent submit, hand-derived ledgers (PERFECT / PARTIAL / BLANK / ATTACKER), fail-closed and teacher review.
// The marks are decided by the LANGUAGE, never the structure: PERFECT answers with machines that differ from the references (other state
// names, a DFA where an NFA was allowed, ε arrows) and gets full marks. Owner decision: full marks or zero.
const require_ = createRequire(import.meta.url);
const { createPlatform } = require_("../certification-20g/platform.js");
const { examOfficialStats } = require_("../../src/lib/exam-structure.js");
const { gradeExam } = require_("../../src/lib/assignment-grading.js");
