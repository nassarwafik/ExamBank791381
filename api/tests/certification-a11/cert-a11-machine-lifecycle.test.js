describe("A11 the grade is the book exercises' judge", () => {
  const book = () => {
    const out = [];
    const walk = v => { if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === "object") { if (v.simulationType === "machine-design" && v.config) out.push(v); else Object.values(v).forEach(walk); } };
    for (const f of fs.readdirSync(path.join(repo, "src/learning/content/899271/modules"))) {
      const src = fs.readFileSync(path.join(repo, "src/learning/content/899271/modules", f), "utf8");
      const json = src.slice(src.indexOf("{", src.indexOf("= ")), src.lastIndexOf("}") + 1);
      try { walk(JSON.parse(json)); } catch { /* a module that is not a plain object literal holds no exercise */ }
    }
    return out;
  };
  const questionOf = t => ({
    v: 1, machine: t.machine, ...(t.mode === "compute" ? { mode: "compute" } : {}), alphabet: t.alphabet, maxStates: t.maxStates ?? 12,
    ...(t.leftEnd ? { leftEnd: true } : {}), ...(t.maxLength ? { maxLength: t.maxLength } : {}),
    ...(t.examples ? { examples: t.mode === "compute" ? { compute: (t.examples.compute ?? []).map(x => ({ word: x.word, output: x.answer })) } : { accept: t.examples.accept ?? [], reject: t.examples.reject ?? [] } } : {}),
  });
  it("the book's 11 push-down / Turing machine «صمّم الآلة» exercises, as exam questions: valid; each reference answering its own question gets full marks", () => {
    const blocks = book();
    expect(blocks.length).toBe(11);
    for (const b of blocks) {
      const config = questionOf(b.config.task);
      const question = { presentationType: "machineDesign", questionTypeVersion: 1, machineDesign: config, answer: { reference: b.config.reference } };
      expect(validateMachineDesignQuestion(question), b.id).toEqual([]);   // the book's examples agree with its reference
      const r = scoreMachineDesign({ config, answerKey: question.answer, response: ans(b.config.reference), maxMarks: 7 });
      expect([r.score, r.correct, r.manualReview], b.id).toEqual([7, true, false]);
      // the same verdict as the book exercise's own check
      const practice = evaluateMachineDesign({ kind: "machine-design", rules: rulesOf(config), reference: b.config.reference }, { kind: "machine-design", machine: b.config.reference });
      expect(r.agreesUpTo, b.id).toEqual(practice.agreesUpTo);
    }
  });
  it("a judge that cannot decide sends the answer to teacher review — never a silent zero", () => {
    const judge = require_("../../src/lib/learning-machine-design.js");
    const gradingPath = require_.resolve("../../src/lib/machine-design-grading.js");
    const real = judge.evaluateMachineDesign;
    try {
      judge.evaluateMachineDesign = () => ({ status: "unavailable" });
      delete require_.cache[gradingPath];
      const { scoreMachineDesign: undecided } = require_(gradingPath);
      const q = qs(load())[0];
      expect(undecided({ config: q.machineDesign, answerKey: q.answer, response: PERFECT.p1, maxMarks: 6 })).toEqual({ score: 0, correct: false, manualReview: true });
    } finally {
      judge.evaluateMachineDesign = real;
      delete require_.cache[gradingPath];
    }
  });
  it("beside the score: the agreement length (full marks), the separating word (a language / a function), the word it did not halt on", () => {
    const e = load(), q = id => qs(e).find(x => x.examQuestionId === id);
    const s = (id, answer) => scoreMachineDesign({ config: q(id).machineDesign, answerKey: q(id).answer, response: answer, maxMarks: q(id).marks });
    expect(s("p1", PERFECT.p1)).toEqual({ score: 6, correct: true, manualReview: false, agreesUpTo: { length: 8, words: 511 } });
    expect(s("t2", PERFECT.t2)).toEqual({ score: 5, correct: true, manualReview: false, agreesUpTo: { length: 10, words: 11 } });
    expect(s("p1", PARTIAL.p1)).toEqual({ score: 0, correct: false, manualReview: false, counterexample: { word: "", shouldAccept: true } });
    expect(s("t2", PARTIAL.t2)).toEqual({ score: 0, correct: false, manualReview: false, counterexample: { word: "1", expected: "111", got: "11" } });
    expect(s("t1", NOHALT.t1)).toEqual({ score: 0, correct: false, manualReview: true, nohalt: { word: "b" } });
    expect(s("p1", ATTACKER.p1)).toEqual({ score: 0, correct: false, manualReview: false, issue: { code: "too-many-states", max: 6 } });
    expect(s("t1", undefined)).toEqual({ score: 0, correct: false, manualReview: false });
    // the book's tape: a machine that first steps onto ├ and back is right on t1 (├ before the input), as on the student's own player
    const detour = { ...R.awb, states: [...R.awb.states, "d1", "d2"], start: "d1", transitions: [tm("d1", "a", "a", "L", "d2"), tm("d1", "b", "b", "L", "d2"), tm("d2", "├", "├", "R", "q0"), ...R.awb.transitions] };
    expect(s("t1", ans(detour))).toMatchObject({ score: 5, correct: true });
    const noEnd = { ...q("t1").machineDesign }; delete noEnd.leftEnd;
    expect(scoreMachineDesign({ config: noEnd, answerKey: q("t1").answer, response: ans(detour), maxMarks: 5 })).toMatchObject({ score: 0, counterexample: { word: "ab", shouldAccept: true } });
    expect(JSON.stringify(s("t2", PARTIAL.t2))).not.toMatch(/"reference"|"q5"/);
  });
});

