// (all-or-nothing: 0) · b3 the parietal lobe · c1 a wrong option. The order a student clicks in never matters (h2/b2 stored in model order).
const PARTIAL = { ...PERFECT, h1: sel("heartChambers", "rightVentricle"), h2: sel("heartVessels", "aorta"), b2: sel("brainStem", "pons", "midbrain"), b3: sel("brainLobes", "parietalLobe"), c1: A.choice(3) };
