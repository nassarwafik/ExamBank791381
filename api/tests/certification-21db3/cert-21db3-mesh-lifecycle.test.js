  ["b1", "MESH_SELECTION_DUPLICATE"], ["b2", "MESH_SELECTION_PART_UNKNOWN"], ["b3", "MESH_SELECTION_ANSWER_INVALID"], ["c1", "MESH_SELECTION_QUESTION_MISMATCH"],
  ["h1", "MESH_SELECTION_ANSWER_INVALID"], ["h2", "MESH_SELECTION_TOO_MANY"], ["h3", "MESH_SELECTION_MODEL_MISMATCH"], ["zz", "MESH_SELECTION_QUESTION_MISMATCH"]
